#!/bin/sh
# Makes generated code and generated schema blocks match the contracts and schemas they come from.
#
#   scripts/generate.sh          regenerate what differs; a second run changes nothing
#   scripts/generate.sh --check  show what differs and change nothing; exits 1 on any difference
#   scripts/generate.sh --check-committed
#                                as --check, for the committed inline schema blocks only (below);
#                                run it before anything regenerates them, or drift is overwritten
#
# Each src/<module>/api/<service>.oapi-codegen.yaml declares one target: code generated from the
# newest contract version under src/<service>/api/{stable,preview}/ (ordered by
# scripts/contract-versions.sh, the rule scripts/contract-diff.sh also uses: by date, then preview
# before stable on the same date; a misnamed version folder fails the run), bundled into one document
# with Redocly CLI, then turned into src/<module>/api/gen/<service>.gen.go by oapi-codegen.
# Generated code is never committed (constitution, Clean tree); builds and checks run this first.
#
# Inline schemas: Docker Agent reads an agent's structured_output schema only inline, and only with
# references inside it (`#...`), so an agent definition carries the self-contained form of a schema
# of ours. A YAML file under src/ declares one such block with a pair of marker lines:
#
#   <indent># BEGIN generated by scripts/generate.sh: <key> from <path>.schema.json
#   <indent># END generated by scripts/generate.sh
#
# Everything between them is replaced by `<indent><key>:` and the schema as JSON (which is YAML),
# indented two more. The schema is <path> (relative to the repository) with every $ref resolved by
# Redocly CLI (`bundle --dereferenced`, through a minimal OpenAPI wrapper, because Redocly bundles
# only API descriptions), without its `$id`, which names the source file and means nothing inline.
# These files are committed, because the definition must carry the schema; --check proves the
# committed block matches.
set -eu
export LC_ALL=C
cd "$(dirname "$0")/.."
# Lists below hold one path per line; split on newlines only, so a name with spaces stays whole.
IFS='
'
set -f
mode=write
[ "${1:-}" = "--check" ] && mode=check
committed_only=
[ "${1:-}" = "--check-committed" ] && { mode=check; committed_only=1; }
pin() { awk -v n="$1" '$1==n{print $2}' src/deploy/images.lock; }
GO_IMAGE=$(pin golang)
OAPI_CODEGEN=$(pin oapi-codegen)
GO_CACHE="${XDG_CACHE_HOME:-$HOME/.cache}/agentic-platform/go"  # module and build cache, outside the repository
mkdir -p "$GO_CACHE"

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$tmp/contracts" "$tmp/out"

targets=$(find src -path 'src/*/api/*.oapi-codegen.yaml' | sort)
[ -n "$committed_only" ] && targets=
# Files that declare inline schema blocks (see above); their gen/ folders are not involved.
BEGIN_MARK='# BEGIN generated by scripts/generate.sh: '
inline=$(grep -rlF --include='*.yaml' -- "$BEGIN_MARK" src | grep -v '/gen/' | sort || true)
[ -z "$targets" ] && [ -z "$inline" ] && { echo "generate: no targets found"; exit 0; }
[ -z "$targets" ] && [ -z "$committed_only" ] && echo "generate: no targets found for oapi-codegen"

for config in $targets; do
  service=$(basename "$config" .oapi-codegen.yaml)
  bundle="$tmp/contracts/$service.openapi.yaml"
  [ -f "$bundle" ] && continue
  versions=$(sh scripts/contract-versions.sh . "$service") \
    || { echo "generate: $config: version folders under src/$service/api/ cannot be ordered" >&2; exit 1; }
  contract=$(printf '%s\n' "$versions" | tail -1 | cut -f2)
  [ -z "$contract" ] && { echo "generate: $config: no contract under src/$service/api/" >&2; exit 1; }
  echo "bundle   $contract"
  NPM_TOOL_MOUNT="$tmp" scripts/npm-tool.sh redocly bundle "$contract" -o "$bundle" >"$tmp/redocly.log" 2>&1 \
    || { cat "$tmp/redocly.log" >&2; exit 1; }
done

# Generate every target into $tmp/out/<module>/api/gen/, in the pinned Go container.
[ -n "$targets" ] && docker run --rm -v "$PWD/src:/src:ro" -v "$tmp:/work" -v "$GO_CACHE:/gopath" \
  -e GOPATH=/gopath -e GOCACHE=/gopath/cache -e GOTOOLCHAIN=local \
  --user "$(id -u):$(id -g)" "$GO_IMAGE" sh -ec '
  go install "$1"
  shift
  for config in "$@"; do
    service=$(basename "$config" .oapi-codegen.yaml)
    dir=$(dirname "$config")
    mkdir -p "/work/out/$dir/gen"
    (cd "/$dir" && /gopath/bin/oapi-codegen -config "$(basename "$config")" \
      -o "/work/out/$dir/gen/$service.gen.go" "/work/contracts/$service.openapi.yaml")
  done' generate "$OAPI_CODEGEN" $targets

# Inline schema blocks: bundle each named schema once, then rewrite each declaring file into
# $tmp/out/<file>, in the pinned Node container without network.
if [ -n "$inline" ]; then
  NODE_IMAGE=$(pin node)
  [ -n "$NODE_IMAGE" ] || { echo "generate: no node pin in src/deploy/images.lock" >&2; exit 1; }
  mkdir -p "$tmp/schemas"
  sources=$(for f in $inline; do grep -F -- "$BEGIN_MARK" "$f"; done \
    | sed -n 's/^.*# BEGIN generated by scripts\/generate\.sh: [A-Za-z_][A-Za-z0-9_]* from \([^ ]*\.schema\.json\)$/\1/p' | sort -u)
  for src in $sources; do
    [ -f "$src" ] || { echo "generate: $src, named by an inline schema block, does not exist" >&2; exit 1; }
    name=$(printf '%s' "$src" | tr '/' '_')
    printf 'openapi: 3.1.0\ninfo: {title: inline schema, version: "1"}\npaths: {}\ncomponents:\n  schemas:\n    Inline:\n      $ref: "%s"\n' \
      "$PWD/$src" >"$tmp/schemas/$name.wrapper.yaml"
    echo "bundle   $src"
    NPM_TOOL_MOUNT="$tmp" scripts/npm-tool.sh redocly bundle "$tmp/schemas/$name.wrapper.yaml" \
      --dereferenced --ext json -o "$tmp/schemas/$name.json" >"$tmp/redocly.log" 2>&1 \
      && [ -s "$tmp/schemas/$name.json" ] || { cat "$tmp/redocly.log" >&2; exit 1; }
  done
  docker run --rm --network none -v "$PWD:$PWD:ro" -v "$tmp:$tmp" -w "$PWD" \
    --user "$(id -u):$(id -g)" "$NODE_IMAGE" node -e '
    const fs = require("fs"), path = require("path");
    const [tmp, ...files] = process.argv.slice(1);
    const begin = /^( *)# BEGIN generated by scripts\/generate\.sh: ([A-Za-z_][A-Za-z0-9_]*) from (\S+\.schema\.json)$/;
    const end = /^ *# END generated by scripts\/generate\.sh$/;
    for (const file of files) {
      const lines = fs.readFileSync(file, "utf8").split("\n"), out = [];
      for (let i = 0; i < lines.length; i++) {
        out.push(lines[i]);
        const m = begin.exec(lines[i]);
        if (!m) { if (end.test(lines[i])) throw new Error(file + ":" + (i + 1) + ": END without BEGIN"); continue; }
        const [, indent, key, src] = m;
        let j = i + 1;
        while (j < lines.length && !end.test(lines[j])) {
          if (begin.test(lines[j])) throw new Error(file + ":" + (j + 1) + ": BEGIN inside a block");
          j++;
        }
        if (j === lines.length) throw new Error(file + ":" + (i + 1) + ": BEGIN without END");
        if (lines[j].length - lines[j].trimStart().length !== indent.length)
          throw new Error(file + ":" + (j + 1) + ": END is not indented like its BEGIN");
        const bundle = JSON.parse(fs.readFileSync(path.join(tmp, "schemas", src.replace(/\//g, "_") + ".json"), "utf8"));
        const schema = bundle.components.schemas.Inline;
        delete schema.$id;
        if (JSON.stringify(schema).includes("\"$ref\"")) throw new Error(src + ": a $ref is left after bundling");
        out.push(indent + key + ":");
        for (const l of JSON.stringify(schema, null, 2).split("\n")) out.push(indent + "  " + l);
        out.push(lines[j]);
        i = j;
      }
      const dest = path.join(tmp, "out", file);
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.writeFileSync(dest, out.join("\n"));
    }' "$tmp" $inline || { echo "generate: an inline schema block cannot be written" >&2; exit 1; }
fi

status=0
for file in $inline; do
  if cmp -s "$file" "$tmp/out/$file"; then
    echo "same     $file"
  elif [ "$mode" = check ]; then
    echo "differs  $file (run scripts/generate.sh)"
    diff -u "$file" "$tmp/out/$file" 2>&1 | head -40 || true
    status=1
  else
    cp "$tmp/out/$file" "$file"
    echo "written  $file"
  fi
done
for gen in $(for config in $targets; do echo "$(dirname "$config")/gen"; done | sort -u); do
  if diff -r "$gen" "$tmp/out/$gen" >/dev/null 2>&1; then
    echo "same     $gen"
  elif [ "$mode" = check ]; then
    echo "differs  $gen (run scripts/generate.sh)"
    diff -ru "$gen" "$tmp/out/$gen" 2>&1 | head -40 || true
    status=1
  else
    rm -rf "$gen"
    cp -R "$tmp/out/$gen" "$gen"
    echo "written  $gen"
  fi
done
exit $status
