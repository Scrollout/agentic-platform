"""Tests for the inline schema blocks of scripts/generate.sh (agent definitions under src/agents/).

Everything runs in throwaway copies of the repository; the real tree is never touched. The
generator, the checks and the hook are the working-tree files, or the files named by
GENERATE_SOURCE, CHECK_SOURCE and PRE_COMMIT_HOOK_SOURCE (for example copies from `git show HEAD:`,
to record that a test fails against the old script). docker and git are prerequisites: a missing
one fails, it is never skipped. Run with
`python3 -m unittest discover -s scripts/tests -p 'test_inline_schema.py'`.
"""
import glob
import json
import os
import re
import shutil
import subprocess
import tempfile
import unittest

import gitenv

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
FIXTURES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures", "inline-schema")
GENERATE = os.environ.get("GENERATE_SOURCE") or os.path.join(REPO, "scripts", "generate.sh")
CHECK = os.environ.get("CHECK_SOURCE") or os.path.join(REPO, "scripts", "check.sh")
HOOK = os.environ.get("PRE_COMMIT_HOOK_SOURCE") or os.path.join(REPO, "scripts", "hooks", "pre-commit")
AGENT = "src/agents/analyst.yaml"
API = "src/engine/api/preview/2026-11-12-preview"
PROPOSAL = API + "/slice-proposal.schema.json"
DEFS = API + "/slice-defs.schema.json"
BEGIN = "# BEGIN generated by scripts/generate.sh: "
END = "# END generated by scripts/generate.sh"


def read(path):
    with open(path, "rb") as f:
        return f.read()


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)


def block(text):
    """The lines between the first BEGIN and END markers of text."""
    lines = text.split("\n")
    b = next(i for i, l in enumerate(lines) if BEGIN in l)
    e = next(i for i, l in enumerate(lines) if i > b and END in l)
    return lines[b + 1:e]


class Base(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        missing = [t for t in ("docker", "git") if shutil.which(t) is None]
        if missing:  # a missing prerequisite is a failure, never a skip
            raise AssertionError("these tests need on PATH: " + ", ".join(missing))
        cls._root = tempfile.mkdtemp(prefix="test-inline-schema-")
        cls.addClassCleanup(shutil.rmtree, cls._root, ignore_errors=True)
        cls.baseline = os.path.join(cls._root, "baseline")
        os.makedirs(os.path.join(cls.baseline, "scripts"))
        for f in ("npm-tool.sh", "contract-versions.sh", "check.sh"):
            if os.path.isfile(os.path.join(REPO, "scripts", f)):
                shutil.copy2(os.path.join(REPO, "scripts", f), os.path.join(cls.baseline, "scripts", f))
        shutil.copy2(GENERATE, os.path.join(cls.baseline, "scripts", "generate.sh"))
        shutil.copy2(CHECK, os.path.join(cls.baseline, "scripts", "check.sh"))
        shutil.copytree(os.path.join(REPO, "scripts", "tools"), os.path.join(cls.baseline, "scripts", "tools"),
                        ignore=shutil.ignore_patterns("node_modules"))
        shutil.copytree(os.path.join(REPO, "src"), os.path.join(cls.baseline, "src"),
                        ignore=shutil.ignore_patterns("gen", "node_modules"))
        # No oapi-codegen target: writes then stay in the inline blocks and need no Go container.
        for c in glob.glob(os.path.join(cls.baseline, "src", "*", "api", "*.oapi-codegen.yaml")):
            os.remove(c)
        if not os.path.isfile(os.path.join(cls.baseline, AGENT)):
            raise AssertionError(AGENT + " does not exist")

    def setUp(self):
        self.work = os.path.join(self._root, "work-%d" % id(self))
        self.addCleanup(shutil.rmtree, self.work, ignore_errors=True)
        shutil.copytree(self.baseline, self.work)

    def p(self, rel):
        return os.path.join(self.work, rel)

    def gen(self, *args, root=None):
        root = root or self.work
        return subprocess.run(["sh", os.path.join(root, "scripts", "generate.sh"), *args], cwd=root,
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=600)

    def out(self, r):
        return r.stdout + r.stderr


class InlineSchemaTest(Base):
    # 1
    def test_committed_block_is_same(self):
        r = self.gen("--check-committed")
        self.assertEqual(r.returncode, 0, self.out(r))
        self.assertIn("same     " + AGENT, r.stdout)

    # 2
    def test_planted_edit_is_found_and_restored_byte_for_byte(self):
        original = read(self.p(AGENT))
        text = original.decode()
        lines = text.split("\n")
        i = next(i for i, l in enumerate(lines) if BEGIN in l) + 3
        lines[i] += " planted"
        write(self.p(AGENT), "\n".join(lines).encode())
        r = self.gen("--check-committed")
        self.assertEqual(r.returncode, 1, self.out(r))
        self.assertIn(AGENT, self.out(r))
        self.assertIn("differs", r.stdout)
        self.assertNotEqual(read(self.p(AGENT)), original)  # --check-committed changes nothing
        r = self.gen()
        self.assertEqual(r.returncode, 0, self.out(r))
        self.assertEqual(read(self.p(AGENT)), original)
        before = read(self.p(AGENT))
        mtime = os.stat(self.p(AGENT)).st_mtime_ns
        r = self.gen()
        self.assertEqual(r.returncode, 0, self.out(r))
        self.assertEqual(read(self.p(AGENT)), before)
        self.assertNotIn("written", r.stdout)
        self.assertEqual(os.stat(self.p(AGENT)).st_mtime_ns, mtime)

    # 3
    def test_source_schema_change_makes_committed_block_stale(self):
        for rel in (PROPOSAL, DEFS):
            with self.subTest(source=rel):
                shutil.rmtree(self.work)
                shutil.copytree(self.baseline, self.work)
                data = read(self.p(rel)).decode()
                self.assertIn('"maxItems": ', data)
                write(self.p(rel), re.sub(r'"maxItems": (\d+)', lambda m: '"maxItems": %d' % (int(m.group(1)) + 1),
                                          data, count=1).encode())
                r = self.gen("--check-committed")
                self.assertEqual(r.returncode, 1, self.out(r))
                self.assertIn(AGENT, self.out(r))

    # 4
    def test_generated_block_has_no_ref_and_no_id(self):
        shutil.copyfile(self.p(AGENT), self.p(AGENT) + ".orig")
        r = self.gen()
        self.assertEqual(r.returncode, 0, self.out(r))
        for label, text in (("committed", read(self.p(AGENT) + ".orig")), ("regenerated", read(self.p(AGENT)))):
            body = "\n".join(block(text.decode()))
            self.assertNotIn("$ref", body, label)
            self.assertNotIn("$id", body, label)
            self.assertIn('"type"', body, label)
        self.assertEqual(read(self.p(AGENT) + ".orig"), read(self.p(AGENT)))
        # the sources do carry them, so the absence above is the generator's doing
        src = read(self.p(PROPOSAL)).decode() + read(self.p(DEFS)).decode()
        self.assertIn("$ref", src)
        # the block is JSON: it parses once the marker lines and the key are cut away
        body = "\n".join(block(read(self.p(AGENT)).decode())).strip()
        self.assertTrue(body.startswith("schema:"))
        json.loads(body[len("schema:"):])

    # 5
    def assert_malformed(self, fixture, message):
        shutil.copyfile(os.path.join(FIXTURES, fixture), self.p("src/agents/malformed.yaml"))
        os.remove(self.p(AGENT))  # only the fixture declares a block
        for args in ((), ("--check-committed",)):
            with self.subTest(args=args):
                before = read(self.p("src/agents/malformed.yaml"))
                r = self.gen(*args)
                self.assertNotEqual(r.returncode, 0, self.out(r))
                self.assertIn(message, r.stderr)
                if "does not exist" not in message:
                    self.assertIn("malformed.yaml", r.stderr + r.stdout)
                self.assertEqual(read(self.p("src/agents/malformed.yaml")), before)

    def test_unmatched_begin(self):
        self.assert_malformed("unmatched-begin.yaml", "BEGIN without END")

    def test_nested_begin(self):
        self.assert_malformed("nested.yaml", "BEGIN inside a block")

    def test_misindented_end(self):
        self.assert_malformed("misindented.yaml", "END is not indented like its BEGIN")

    def test_end_without_begin_is_not_silently_kept(self):
        # An END line alone is not a block (no BEGIN, so no file is picked up): nothing to write.
        shutil.copyfile(os.path.join(FIXTURES, "end-only.yaml"), self.p("src/agents/malformed.yaml"))
        # next to a real block, the file is read by the generator only if it holds a BEGIN
        with open(self.p("src/agents/malformed.yaml"), "a") as f:
            f.write("  " + BEGIN + "schema from " + DEFS + "\n  " + END + "\n  " + END + "\n")
        r = self.gen("--check-committed")
        self.assertNotEqual(r.returncode, 0, self.out(r))
        self.assertIn("END without BEGIN", r.stderr)

    def test_unknown_schema_path(self):
        self.assert_malformed("unknown-path.yaml", "does not exist")
        r = self.gen()
        self.assertIn("no-such.schema.json", r.stderr)


class CheckOrderTest(Base):
    def test_structural_committed_check_precedes_regeneration(self):
        text = read(self.p("scripts/check.sh")).decode()
        body = text[text.index("go_checks() {"):]
        lines = [l.strip() for l in body.split("\n")]
        committed = lines.index("scripts/generate.sh --check-committed")
        regenerate = lines.index("scripts/generate.sh")
        self.assertLess(committed, regenerate)

    def test_drifted_block_fails_before_regeneration(self):
        original = read(self.p(AGENT))
        lines = original.decode().split("\n")
        i = next(i for i, l in enumerate(lines) if BEGIN in l) + 3
        lines[i] += " planted"
        drifted = "\n".join(lines).encode()
        write(self.p(AGENT), drifted)
        r = subprocess.run(["sh", "scripts/check.sh", "--go-only"], cwd=self.work, stdout=subprocess.PIPE,
                           stderr=subprocess.PIPE, text=True, timeout=600)
        self.assertEqual(r.returncode, 1, self.out(r))
        self.assertIn("differs  " + AGENT, r.stdout)
        self.assertNotIn("== generated code", r.stdout)  # the later step never started
        self.assertEqual(read(self.p(AGENT)), drifted)    # and nothing overwrote the drift


class HookTest(unittest.TestCase):
    def setUp(self):
        missing = [t for t in ("docker", "git") if shutil.which(t) is None]
        if missing:
            self.fail("these tests need on PATH: " + ", ".join(missing))
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        home = os.path.join(tmp.name, "home")
        os.makedirs(home)
        self.env = gitenv.clean_env(home)
        self.clone = os.path.join(tmp.name, "clone")
        subprocess.run(["git", "clone", "--quiet", "--no-hardlinks", REPO, self.clone], check=True,
                       env=self.env, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        self.git("config", "user.name", "Test User")
        self.git("config", "user.email", "test@example.com")
        # The clone holds HEAD; lay the working-tree files under test over it and commit them, so
        # they are the committed state and only the test's own change is staged.
        for rel in ("scripts/hooks/pre-commit", "scripts/generate.sh", "scripts/check.sh"):
            src = {"scripts/hooks/pre-commit": HOOK, "scripts/generate.sh": GENERATE,
                   "scripts/check.sh": CHECK}[rel]
            shutil.copyfile(src, os.path.join(self.clone, rel))
        for rel in ("scripts/npm-tool.sh", "scripts/contract-versions.sh", AGENT, API + "/slice-proposal.schema.json",
                    DEFS):
            if os.path.isfile(os.path.join(REPO, rel)):
                write(os.path.join(self.clone, rel), read(os.path.join(REPO, rel)))
        if os.path.isdir(os.path.join(REPO, "src/agents/analyst")):
            shutil.rmtree(os.path.join(self.clone, "src/agents/analyst"), ignore_errors=True)
            shutil.copytree(os.path.join(REPO, "src/agents/analyst"), os.path.join(self.clone, "src/agents/analyst"))
        os.chmod(os.path.join(self.clone, "scripts/hooks/pre-commit"), 0o755)
        self.git("add", "-A", "-f")
        # In a snapshot repository HEAD already holds these files: commit only if something differs.
        if subprocess.run(["git", "diff", "--cached", "--quiet"], cwd=self.clone, env=self.env).returncode:
            self.git("commit", "-q", "--no-verify", "-m", "test setup: files under test")
        self.hook = os.path.join(self.clone, "scripts", "hooks", "pre-commit")

    def git(self, *args):
        return subprocess.run(["git", *args], cwd=self.clone, check=True, env=self.env,
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)

    def stage_agent(self, mutate):
        path = os.path.join(self.clone, AGENT)
        write(path, mutate(read(path).decode()).encode())
        self.git("add", AGENT)

    def run_hook(self):
        return subprocess.run([self.hook], cwd=self.clone, env=self.env, stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE, text=True, timeout=900)

    def test_staged_agent_with_drifted_block_fails_the_hook(self):
        def drift(t):
            lines = t.split("\n")
            i = next(i for i, l in enumerate(lines) if BEGIN in l) + 3
            lines[i] += " planted"
            return "\n".join(lines)
        self.stage_agent(drift)
        r = self.run_hook()
        out = r.stdout + r.stderr
        self.assertEqual(r.returncode, 1, out)
        self.assertIn("committed generated blocks", out)
        self.assertIn("differs  " + AGENT, out)

    def test_staged_agent_outside_the_block_passes_and_runs_the_check(self):
        self.stage_agent(lambda t: "# a new comment above the definition\n" + t)
        r = self.run_hook()
        out = r.stdout + r.stderr
        self.assertEqual(r.returncode, 0, out)
        self.assertIn("committed generated blocks", out)
        self.assertIn("same     " + AGENT, out)

    def test_unrelated_staged_file_does_not_run_the_check(self):
        write(os.path.join(self.clone, "src/agents/notes.txt"), b"a note\n")
        self.git("add", "src/agents/notes.txt")
        r = self.run_hook()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertNotIn("committed generated blocks", r.stdout + r.stderr)


if __name__ == "__main__":
    unittest.main()
