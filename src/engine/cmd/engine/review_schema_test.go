package main

// T049c: the review agent's findings schema is generated into review.yaml from
// src/agents/review/findings.schema.json (scripts/generate.sh), and that source agrees with
// machine.Finding, the type the engine reads the answer into. Written by a separate author.

import (
	"encoding/json"
	"os"
	"reflect"
	"regexp"
	"sort"
	"strings"
	"testing"

	"github.com/agentic-platform/engine/machine"
)

const (
	reviewYAML      = "../../../agents/review.yaml"
	findingsSource  = "../../../agents/review/findings.schema.json"
	findingsSrcPath = "src/agents/review/findings.schema.json"
)

func TestReviewYAMLHoldsTheGeneratedFindingsSchema(t *testing.T) {
	b, err := os.ReadFile(reviewYAML)
	if err != nil {
		t.Fatal(err)
	}
	m := regexp.MustCompile(`(?m)^\s*# BEGIN generated by scripts/generate\.sh: (\S+) from (\S+\.schema\.json)\s*$`).FindSubmatch(b)
	if m == nil {
		t.Fatal("review.yaml has no `# BEGIN generated by scripts/generate.sh: <key> from <path>.schema.json` marker")
	}
	if string(m[1]) != "schema" || string(m[2]) != findingsSrcPath {
		t.Errorf("the block is %q from %q, want schema from %s", m[1], m[2], findingsSrcPath)
	}
	if !strings.Contains(string(b), "# END generated by scripts/generate.sh") {
		t.Error("review.yaml has no END marker")
	}
	if _, err := os.Stat(findingsSource); err != nil {
		t.Errorf("the source schema is missing: %v", err)
	}
}

func TestFindingsSchemaMatchesMachineFinding(t *testing.T) {
	b, err := os.ReadFile(findingsSource)
	if err != nil {
		t.Fatal(err)
	}
	var s struct {
		Properties struct {
			Findings struct {
				Items struct {
					Required   []string                   `json:"required"`
					Properties map[string]json.RawMessage `json:"properties"`
				} `json:"items"`
			} `json:"findings"`
		} `json:"properties"`
	}
	if err := json.Unmarshal(b, &s); err != nil {
		t.Fatal(err)
	}
	item := s.Properties.Findings.Items

	fields, mustHave := map[string]bool{}, []string{}
	ft := reflect.TypeOf(machine.Finding{})
	for i := 0; i < ft.NumField(); i++ {
		name, opts, _ := strings.Cut(ft.Field(i).Tag.Get("json"), ",")
		fields[name] = true
		if !strings.Contains(opts, "omitempty") {
			mustHave = append(mustHave, name)
		}
	}
	req := map[string]bool{}
	for _, r := range item.Required {
		req[r] = true
		if !fields[r] {
			t.Errorf("required field %q is not a machine.Finding JSON field", r)
		}
	}
	for p := range item.Properties {
		if !fields[p] {
			t.Errorf("property %q is not a machine.Finding JSON field", p)
		}
	}
	sort.Strings(mustHave)
	for _, f := range mustHave {
		if !req[f] {
			t.Errorf("machine.Finding always carries %q, but the schema does not require it", f)
		}
	}
	// The model must give what the engine reads to confirm a finding.
	for _, f := range []string{"rule", "file", "line", "text", "blocking"} {
		if !req[f] {
			t.Errorf("%q is not required", f)
		}
	}
}
