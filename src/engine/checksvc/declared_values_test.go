// T005 (feature 009): failing tests, by a separate author, for runCheck serving the two
// declared-value checks DeclaredValuesGenerated and DeclaredValuesNotRepeated. Both judge against
// the text inside the `contract` entry of `approved` (its content is the canonical JSON
// {"contract": "<text>"}), never api/openapi.yaml in the project folder (check contract, runCheck;
// catalogue README, "Declared values"). The checks run no Go, so no toolchain or oapi-codegen is
// needed. Over HTTP only, requests as plain JSON maps.
package checksvc_test

import (
	"strings"
	"testing"
)

// dvContract is a contract that declares one value: maxLength under NewNote's text property.
func dvContract(maxLength string) string {
	return "openapi: 3.0.3\ninfo:\n  title: Notes\n  version: \"1\"\npaths: {}\ncomponents:\n  schemas:\n" +
		"    NewNote:\n      type: object\n      properties:\n        text:\n          type: string\n" +
		"          maxLength: " + maxLength + "\n"
}

// dvDeclared is gen/declared.go as the generate procedure renders it for dvContract(n) (contract
// draft, "gen/declared.go").
func dvDeclared(n string) string {
	return "// Code generated by the generate procedure from api/openapi.yaml. DO NOT EDIT.\n\npackage gen\n\n" +
		"// DeclaredNewNoteTextMaxLength is declared at \"/components/schemas/NewNote/properties/text/maxLength\".\n" +
		"const DeclaredNewNoteTextMaxLength = " + n + "\n"
}

var (
	dvGenStep  = step("generate", []string{"gen/**"}, []string{"generated-code"}, nil, nil)
	dvCodeStep = step("code", []string{"internal/**"}, []string{"code"}, nil, nil)
)

// dvStepFor is the step each check judges.
func dvStepFor(check string) map[string]any {
	if check == "DeclaredValuesNotRepeated" {
		return dvCodeStep
	}
	return dvGenStep
}

var dvChecks = []string{"DeclaredValuesGenerated", "DeclaredValuesNotRepeated"}

// dvBody is a runCheck body whose approved contract is the text `contract`; the project folder
// (api/openapi.yaml, gen/declared.go, internal/) is the caller's.
func dvBody(t testing.TB, dir string, st map[string]any, contract string) map[string]any {
	t.Helper()
	return checkBody(t, dir, st, nil, contract, approvedExamples(t))
}

// dvRawContractPart replaces the approved `contract` entry by one whose content is raw bytes,
// with their correct sha256 (so the request passes the hash check and only the content is wrong).
func dvRawContractPart(body map[string]any, raw string) {
	for _, a := range body["approved"].([]any) {
		if p := a.(map[string]any); p["part"] == "contract" {
			p["content"], p["sha256"] = b64([]byte(raw)), sum([]byte(raw))
		}
	}
}

func TestDeclaredValueChecksAreServed(t *testing.T) {
	root, dir := fixture(t)
	write(t, dir, "gen/declared.go", []byte(dvDeclared("200")))
	write(t, dir, "internal/note.go", []byte("package internal\n"))
	base := serve(t, checkConfig(t, root))
	for _, c := range dvChecks {
		r := post(t, base, "/checks/"+c+"/run", dvBody(t, dir, dvStepFor(c), dvContract("200")))
		if r.status == 404 {
			t.Errorf("%s must be served, not 404 UnknownCheck: %.300s", c, r.body)
			continue
		}
		if v := wantVerdict(t, r, c); !v.Passed {
			t.Errorf("%s must pass for a clean project: %s", c, v.Reason)
		}
	}
}

func TestDeclaredValuesGeneratedJudgesTheApprovedContract(t *testing.T) {
	root, dir := fixture(t)
	// The folder contract declares 300; gen/declared.go matches the approved contract (200).
	write(t, dir, "api/openapi.yaml", []byte(dvContract("300")))
	write(t, dir, "gen/declared.go", []byte(dvDeclared("200")))
	base := serve(t, checkConfig(t, root))
	v := runCheck(t, base, "DeclaredValuesGenerated", dvBody(t, dir, dvGenStep, dvContract("200")))
	if !v.Passed || !strings.Contains(v.Reason, "equals the 1 declared values of the approved contract") {
		t.Fatalf("gen/declared.go equals the approved contract's values, whatever the folder copy says: %+v", v)
	}

	// The reverse: gen/declared.go matches the folder copy (300) but not the approved contract.
	write(t, dir, "gen/declared.go", []byte(dvDeclared("300")))
	v = runCheck(t, base, "DeclaredValuesGenerated", dvBody(t, dir, dvGenStep, dvContract("200")))
	if v.Passed || !strings.Contains(v.Reason, "gen/declared.go") {
		t.Fatalf("a file that matches only the folder's contract must fail, naming gen/declared.go: %+v", v)
	}
}

func TestDeclaredValuesGeneratedFailsNamingAMissingFile(t *testing.T) {
	root, dir := fixture(t)
	write(t, dir, "api/openapi.yaml", []byte(dvContract("200")))
	write(t, dir, "gen/other.go", []byte("package gen\n"))
	base := serve(t, checkConfig(t, root))
	v := runCheck(t, base, "DeclaredValuesGenerated", dvBody(t, dir, dvGenStep, dvContract("200")))
	if v.Passed || !strings.Contains(v.Reason, "gen/declared.go") {
		t.Fatalf("a missing gen/declared.go must fail, naming it: %+v", v)
	}
}

func TestDeclaredValuesNotRepeatedJudgesTheApprovedContract(t *testing.T) {
	root, dir := fixture(t)
	// The folder contract declares 300 only; the approved contract declares 200 only.
	write(t, dir, "api/openapi.yaml", []byte(dvContract("300")))
	base := serve(t, checkConfig(t, root))

	// Repeats the approved value: fails even though the folder copy declares something else.
	write(t, dir, "internal/note.go", []byte("package internal\n\nfunc tooLong(t string) bool { return len(t) > 200 }\n"))
	v := runCheck(t, base, "DeclaredValuesNotRepeated", dvBody(t, dir, dvCodeStep, dvContract("200")))
	for _, want := range []string{"internal/note.go:3", "200", "/components/schemas/NewNote/properties/text/maxLength", "gen.DeclaredNewNoteTextMaxLength"} {
		if v.Passed || !strings.Contains(v.Reason, want) {
			t.Fatalf("a literal repeating the approved contract's value must fail, naming %q: %+v", want, v)
		}
	}

	// Repeats only the folder copy's value: passes, the folder copy is not consulted.
	write(t, dir, "internal/note.go", []byte("package internal\n\nfunc tooLong(t string) bool { return len(t) > 300 }\n"))
	v = runCheck(t, base, "DeclaredValuesNotRepeated", dvBody(t, dir, dvCodeStep, dvContract("200")))
	if !v.Passed || !strings.Contains(v.Reason, "none repeated") {
		t.Fatalf("a literal equal only to the folder contract's value must pass: %+v", v)
	}
}

// A request whose `contract` entry has the right hash but not the content {"contract": "<text>"}
// fails closed: the check does not fall back to the folder's api/openapi.yaml, which here would
// give a clean verdict, and it names the contract it could not read.
func TestDeclaredValueChecksFailClosedOnUnreadableApprovedContract(t *testing.T) {
	root, dir := fixture(t)
	write(t, dir, "api/openapi.yaml", []byte(dvContract("200")))
	write(t, dir, "gen/declared.go", []byte(dvDeclared("200")))
	write(t, dir, "internal/note.go", []byte("package internal\n"))
	base := serve(t, checkConfig(t, root))
	bad := map[string]string{
		"a JSON string":              `"` + strings.ReplaceAll(dvContract("200"), "\n", `\n`) + `"`,
		"an object without contract": `{"text":"x"}`,
		"an empty object":            `{}`,
		"contract a number":          `{"contract":200}`,
		"contract null":              `{"contract":null}`,
		"not JSON":                   dvContract("200"),
		"contract not one document":  `{"contract":"a: 1\na: 2\n"}`,
	}
	for _, c := range dvChecks {
		// Control: the same project and check with a good contract part passes.
		if v := runCheck(t, base, c, dvBody(t, dir, dvStepFor(c), dvContract("200"))); !v.Passed {
			t.Errorf("%s: the control request must pass: %s", c, v.Reason)
		}
		for name, raw := range bad {
			body := dvBody(t, dir, dvStepFor(c), dvContract("200"))
			dvRawContractPart(body, raw)
			r := post(t, base, "/checks/"+c+"/run", body)
			if r.status != 200 {
				if r.status < 400 {
					t.Errorf("%s, approved contract %s: status %d is neither a verdict nor an error", c, name, r.status)
				}
				continue // an error status is closed too
			}
			v := wantVerdict(t, r, c)
			if v.Passed || !strings.Contains(strings.ToLower(v.Reason), "contract") {
				t.Errorf("%s, approved contract %s: must fail closed naming the contract: %+v", c, name, v)
			}
		}
	}
}
