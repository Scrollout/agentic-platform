const (
	cpBase     = "api-feature-go"
	cpName     = "notes"
	cpID       = cpBase + "-" + cpName
	cpProofOf  = "S-2" // the proof slice: the next slice ID after the source slice S-1
	cpSourceS  = "S-1"
	cpFillOnly = "contract-check,generate" // the steps that still need a worker
)

// cpEmpty is the hash of an empty set of files (a clean review's witnesses).
var cpEmpty = canonical.FramedHash(nil)

// cpRig is the engine rig with the real workflow, grants for the source and the proof slice, and a
// step worker that writes framed files.
type cpRig struct {
	*runsRig
	mu           sync.Mutex
	generateAs   string // what generate writes (default: the source run's bytes)
	failCheck    string // "<step>/<check>" that fails
	failWorker   string // a step whose worker call fails
	checks       int    // checks run so far
	sourceChecks int    // checks run before the proofs
	gate         chan struct{}
}

func newCP(t *testing.T) *cpRig {
	t.Helper()
	st, err := store.Open(t.TempDir(), spSchemas(t))
	if err != nil {
		t.Fatal(err)
	}
	sp := newSP(t, []spResult{{p: spNotes(t)}}, st)
	sp.approveAfterSeed(t)
	x := &runsRig{t: t, sp: sp, st: st, projects: t.TempDir(), w: &fakeStepWorker{st: st, data: map[string][]byte{}}, c: &fakeStepChecker{}}
	c := &cpRig{runsRig: x}
	c.boot()
	registerAll(t, x.r, cpSourceS)
	x.w.set(c.work)
	x.c.set(c.check)
	return c
}

// boot makes a handler over the same slices service and store, as an engine restart does.
func (c *cpRig) boot() {
	ctx, cancel := context.WithCancel(context.Background())
	x := c.runsRig
	x.r = newRig(x.t, func(cfg *Config) {
		cfg.Context = ctx
		cfg.Slices, cfg.Store = x.sp.svc, x.st
		cfg.WorkerGrants = mergeGrants(stepGrants(cpSourceS), stepGrants(cpProofOf))
		cfg.Projects = x.projects
		cfg.Model = "test-model"
		cfg.StepWorker, cfg.StepChecker = x.w, x.c
	})
	stopEngineAtEnd(x.t, x.r, cancel)
}

var cpFiles = map[string][]canonical.File{
	"tests":     {{Path: "tests/note_test.go", Content: []byte("package tests // note\n")}},
	"code":      {{Path: "internal/app/note.go", Content: []byte("package app // note\n")}},
	"witnesses": nil,
}

// work writes framed files for the outputs a capture keeps and the plain default for the rest.
func (c *cpRig) work(ctx context.Context, r machine.Request) (machine.Result, error) {
	c.mu.Lock()
	gate, failWorker, generateAs := c.gate, c.failWorker, c.generateAs
	c.mu.Unlock()
	if gate != nil {
		select {
		case <-gate:
		case <-ctx.Done():
			return machine.Result{}, ctx.Err()
		}
	}
	if r.Step.Name == failWorker {
		return machine.Result{}, context.DeadlineExceeded
	}
	res, err := c.w.produce(r)
	if err != nil {
		return res, err
	}
	for _, o := range r.Step.Outputs {
		files, ok := cpFiles[o]
		if !ok {
			continue
		}
		h, err := c.st.PutArtifact(cpSourceS, canonical.Framed(files))
		if err != nil {
			return res, err
		}
		res.Outputs[o] = h
		for _, f := range files {
			sum := sha256.Sum256(f.Content)
			res.ProjectFiles = append(res.ProjectFiles, machine.File{Path: f.Path, SHA256: hex.EncodeToString(sum[:])})
		}
	}
	if generateAs != "" && r.Step.Name == "generate" { // generated code that differs from the source run's
		h, err := c.st.PutArtifact(cpSourceS, []byte(generateAs))
		if err != nil {
			return res, err
		}
		res.Outputs["generated-code"] = h
	}
	return res, nil
}

func (c *cpRig) check(_ context.Context, r machine.CheckRequest) (machine.CheckResult, error) {
	c.mu.Lock()
	fail := c.failCheck
	c.checks++
	c.mu.Unlock()
	if fail != "" && fail == r.Step.Name+"/"+r.Name {
		return machine.CheckResult{Passed: false, Reason: r.Name + " does not hold"}, nil
	}
	return machine.CheckResult{Passed: true}, nil
}

func (c *cpRig) set(f func()) { c.mu.Lock(); f(); c.mu.Unlock() }

func (c *cpRig) opBody(p reply, status int) gen.Operation {
	c.t.Helper()
	if p.Code != status {
		c.t.Fatalf("status = %d, want %d: %s", p.Code, status, p.Body.String())
	}
	var op gen.Operation
	if err := json.Unmarshal(p.Body.Bytes(), &op); err != nil {
		c.t.Fatalf("not an operation: %v: %s", err, p.Body.String())
	}
	return op
}

func (c *cpRig) problem(p reply, status int, code gen.ErrorCode) {
	c.t.Helper()
	p.problem(c.t, status, code)
}

// capture runs the source slice to done and captures it; it returns the captured pattern.
func (c *cpRig) capture() gen.CapturedPattern {
	c.t.Helper()
	src := c.runDone("source-app")
	op := c.opBody(c.do("POST", apiPath("/captured-patterns"), `{"run":"`+src.ID+`","name":"`+cpName+`"}`), 202)
	if op.Target != cpID {
		c.t.Fatalf("the capture's target = %q, want %q", op.Target, cpID)
	}
	if got := c.waitOp(op.Id); got.Status != "succeeded" {
		c.t.Fatalf("capture ended %+v", got)
	}
	return c.pattern()
}

func (c *cpRig) pattern() gen.CapturedPattern {
	c.t.Helper()
	p := c.do("GET", apiPath("/captured-patterns/"+cpID), "")
	if p.Code != http.StatusOK {
		c.t.Fatalf("getCapturedPattern = %d: %s", p.Code, p.Body.String())
	}
	var cp gen.CapturedPattern
	if err := json.Unmarshal(p.Body.Bytes(), &cp); err != nil {
		c.t.Fatal(err)
	}
	return cp
}

// proofSlice makes (or gets) the proof slice and registers the workers it still needs: a fill
// step needs none, so the others only.
func (c *cpRig) proofSlice() string {
	c.t.Helper()
	op := c.opBody(c.do("POST", apiPath("/captured-patterns/"+cpID+"/proof-slice"), ""), 202)
	got := c.waitOp(op.Id)
	if got.Status != "succeeded" || got.Result["slice"] == "" {
		c.t.Fatalf("proof-slice ended %+v", got)
	}
	for _, s := range strings.Split(cpFillOnly, ",") {
		if w := register(c.r, stepToken(got.Result["slice"], s), endpointFor(s)); w.Code != 200 {
			c.t.Fatalf("register %s: %d %s", s, w.Code, w.Body.String())
		}
	}
	return got.Result["slice"]
}

func (c *cpRig) startProof(slice, project string) reply {
	return c.do("POST", spURL(slice, "/runs"), `{"project":"`+project+`"}`)
}

// prove starts a proof run and returns its operation.
func (c *cpRig) prove(project string) spOp {
	c.t.Helper()
	return c.opOf(c.startProof(c.proofSlice(), project), "run")
}

func (c *cpRig) rawEvents(run string) []map[string]any {
	c.t.Helper()
	p := c.do("GET", apiPath("/runs/"+run+"/events"), "")
	var pg struct {
		Items []map[string]any `json:"items"`
	}
	if p.Code != 200 || json.Unmarshal(p.Body.Bytes(), &pg) != nil {
		c.t.Fatalf("listRunEvents = %d: %s", p.Code, p.Body.String())
	}
	return pg.Items
}

func (c *cpRig) lastProof(cp gen.CapturedPattern) gen.Proof {
	c.t.Helper()
	if len(cp.Proofs) == 0 {
		c.t.Fatalf("the captured pattern has no proof: %+v", cp)
	}
	return cp.Proofs[len(cp.Proofs)-1]
}

func (c *cpRig) getRunView(id string) gen.Run {
	c.t.Helper()
	p := c.do("GET", apiPath("/runs/"+id), "")
	var r gen.Run
	if p.Code != 200 || json.Unmarshal(p.Body.Bytes(), &r) != nil {
		c.t.Fatalf("getRun %s = %d: %s", id, p.Code, p.Body.String())
	}
	return r
}

func cpValues(cp gen.CapturedPattern) map[string]string {
	out := map[string]string{}
	for _, p := range cp.Parameters {
		out[p.Name] = p.Value
	}
	return out
}

// A proof is a startRun of the proof slice under the captured pattern with the source values; its
// RunStarted names the captured pattern, `chosen`, the source run and `proof: true`; a fill step
// needs no registered worker; no agent worker and no model call is made; the proof passes when the
// run ends done and tests, code and witnesses equal the template's hashes (witnesses empty here).
func TestAProofIsARunOfTheProofSliceThatPassesOnTheTemplateHashes(t *testing.T) {
	c := newCP(t)
	cp := c.capture()
	if cp.Template.Witnesses != cpEmpty {
		t.Fatalf("setup: the template's witnesses = %s, want the empty set's %s", cp.Template.Witnesses, cpEmpty)
	}
	before := c.w.callCount()
	op := c.prove("proof-app")
	run := c.waitEnded(op.Target, "done")
	if got := c.w.callCount() - before; got != 2 {
		t.Errorf("the proof made %d worker calls, want 2 (contract-check and generate): a fill step makes no agent or model call", got)
	}
	if c.w.calls[before] != "contract-check" || c.w.calls[before+1] != "generate" {
		t.Errorf("worker calls %v, want contract-check then generate", c.w.calls[before:])
	}
	v := c.getRunView(run.ID)
	if v.Proof == nil || !bool(*v.Proof) || v.Pattern != cpID+"@1.0.0" || v.PatternReason == nil || *v.PatternReason != gen.PatternReasonChosen ||
		v.SourceRun == nil || *v.SourceRun != cp.Source.Run || v.Slice != cpProofOf {
		t.Errorf("the proof run = %+v, want proof, pattern %s@1.0.0, reason chosen, source run %s, slice %s", v, cpID, cp.Source.Run, cpProofOf)
	}
	started := c.rawEvents(run.ID)[0]
	if started["kind"] != "RunStarted" || started["pattern"] != cpID+"@1.0.0" || started["pattern_reason"] != "chosen" ||
		started["source_run"] != cp.Source.Run || started["proof"] != true {
		t.Errorf("RunStarted = %v, want it to name the captured pattern, chosen, the source run and proof true", started)
	}
	if got, _ := json.Marshal(started["parameters"]); string(got) != cpJSON(t, cpValues(cp)) && len(cp.Parameters) > 0 {
		t.Errorf("RunStarted parameters = %s, want the source values %s", got, cpJSON(t, cpValues(cp)))
	}
	hashes := map[string]string{}
	for _, e := range c.allEvents(run.ID) {
		if e.Kind == "StepAccepted" && len(e.Artifacts) == 1 {
			hashes[e.Step] = e.Artifacts[0]
		}
	}
	if hashes["tests"] != cp.Template.Tests || hashes["code"] != cp.Template.Code || hashes["review"] != cp.Template.Witnesses {
		t.Errorf("accepted hashes %v, want tests %s code %s witnesses %s", hashes, cp.Template.Tests, cp.Template.Code, cp.Template.Witnesses)
	}
	read := c.pattern() // right after the run's end line, with no wait
	pr := c.lastProof(read)
	if pr.Outcome != gen.ProofOutcomePassed || pr.Run != run.ID || len(pr.Failures) != 0 || pr.Method != cp.Method ||
		cpJSON(t, pr.Parameters) != cpJSON(t, cpValues(cp)) {
		t.Errorf("the proof = %+v, want passed, run %s, method %s, the source values, no failure", pr, run.ID, cp.Method)
	}
	if read.State != gen.CapturedPatternStateProven || read.Usable {
		t.Errorf("state %s usable %v after a passing proof, want proven and not usable (not approved)", read.State, read.Usable)
	}
}

func cpJSON(t *testing.T, v any) string {
	t.Helper()
	b, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

