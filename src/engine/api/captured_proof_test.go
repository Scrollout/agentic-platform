// A failing check fails the proof at once naming step and check, while the run waits; the fill
// step is not attempted again; the captured pattern is not proven.
func TestAFailingCheckFailsTheProofAtOnceNamingStepAndCheck(t *testing.T) {
	c := newCP(t)
	c.capture()
	c.set(func() { c.failCheck = "tests/TestsBuild" })
	var mu sync.Mutex
	runs := 0
	inner := c.check
	c.c.set(func(ctx context.Context, r machine.CheckRequest) (machine.CheckResult, error) {
		if r.Step.Name == "tests" && r.Name == "TestsBuild" {
			mu.Lock()
			runs++
			mu.Unlock()
		}
		return inner(ctx, r)
	})
	op := c.prove("proof-app")
	c.waitStatus(op.Target, "waiting-for-developer")
	cp := c.pattern()
	p := c.lastProof(cp)
	if p.Outcome != gen.ProofOutcomeFailed || len(p.Failures) == 0 || p.Failures[0].Step == nil || *p.Failures[0].Step != "tests" ||
		p.Failures[0].Check == nil || *p.Failures[0].Check != "TestsBuild" {
		t.Errorf("the proof = %+v, want failed at once naming step tests and check TestsBuild", p)
	}
	if cp.State == gen.CapturedPatternStateProven || cp.Usable {
		t.Errorf("state %s usable %v after a failed proof", cp.State, cp.Usable)
	}
	mu.Lock()
	defer mu.Unlock()
	if runs != 1 {
		t.Errorf("TestsBuild ran %d times for the fill step, want once: a fill step is never attempted twice", runs)
	}
	// the failed proof's run waits for the developer: PUT /parameters is busy until it ends
	body := `{"parameters":[]}`
	c.problem(c.do("PUT", apiPath("/captured-patterns/"+cpID+"/parameters"), body), 409, "CapturedPatternBusy")
}

// An expired or cancelled proof run fails the proof naming the end.
func TestAnExpiredOrCancelledProofRunFailsTheProofNamingTheEnd(t *testing.T) {
	for _, end := range []string{"cancelled", "expired"} {
		t.Run(end, func(t *testing.T) {
			c := newCP(t)
			c.capture()
			c.set(func() { c.failCheck = "tests/TestsBuild" }) // the run waits for the developer
			op := c.prove("proof-app")
			c.waitStatus(op.Target, "waiting-for-developer")
			if end == "cancelled" {
				c.opBody(c.do("POST", apiPath("/operations/"+op.ID+"/cancel"), ""), 202)
			} else {
				waitForTimer(t, c.st, op.Target)
				c.r.clock.Advance(14*24*time.Hour + time.Hour)
			}
			c.waitEnded(op.Target, end)
			p := c.lastProof(c.pattern())
			if p.Outcome != gen.ProofOutcomeFailed || len(p.Failures) == 0 || !strings.Contains(p.Failures[len(p.Failures)-1].Reason, end) {
				t.Errorf("the proof = %+v, want failed naming %q", p, end)
			}
		})
	}
}

