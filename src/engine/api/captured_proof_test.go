// A Proof whose parameters differ from the current ones neither makes the pattern proven nor
// counts for approval; PUT /parameters moves a proven one back to proposed, also when it leaves
// the same values.
func TestParametersChangeMovesAProvenPatternBackAndAnOldProofDoesNotCountForApproval(t *testing.T) {
	c := newCP(t)
	cp := c.capture()
	op := c.prove("proof-app")
	c.waitEnded(op.Target, "done")
	if got := c.pattern(); got.State != gen.CapturedPatternStateProven {
		t.Fatalf("setup: state %s, want proven", got.State)
	}
	put := func(params []gen.ParameterValueRequest) {
		t.Helper()
		b, _ := json.Marshal(gen.ParametersRequest{Parameters: params})
		got := c.waitOp(c.opBody(c.do("PUT", apiPath("/captured-patterns/"+cpID+"/parameters"), string(b)), 202).Id)
		if got.Status != "succeeded" {
			t.Fatalf("replaceParameters ended %+v", got)
		}
	}
	same := make([]gen.ParameterValueRequest, 0, len(cp.Parameters))
	for _, p := range cp.Parameters {
		same = append(same, gen.ParameterValueRequest{Name: p.Name, Value: p.Value})
	}
	put(same) // the same values
	if got := c.pattern(); got.State != gen.CapturedPatternStateProposed {
		t.Errorf("state %s after a PUT that leaves the same values, want proposed", got.State)
	}
	c.problem(c.do("POST", apiPath("/captured-patterns/"+cpID+"/approval"), ""), 409, "ProofRequired")
	put([]gen.ParameterValueRequest{{Name: "kept-item", Value: "note"}}) // other values: the old proof proved other parameters
	got := c.pattern()
	if got.State != gen.CapturedPatternStateProposed || got.Usable {
		t.Errorf("state %s usable %v after other parameters, want proposed", got.State, got.Usable)
	}
	c.problem(c.do("POST", apiPath("/captured-patterns/"+cpID+"/approval"), ""), 409, "ProofRequired")
}

// Approval needs a passing proof first (ProofRequired before it); it records by `client`, at and
// the proof; an approved captured pattern refuses PUT /parameters with 409 CapturedPatternApproved
// and approving again changes nothing.
func TestApprovalNeedsAPassingProofAndRecordsClientTimeAndProof(t *testing.T) {
	c := newCP(t)
	c.capture()
	c.problem(c.do("POST", apiPath("/captured-patterns/"+cpID+"/approval"), ""), 409, "ProofRequired")
	op := c.prove("proof-app")
	c.waitEnded(op.Target, "done")
	at := c.r.clock.Now()
	if got := c.waitOp(c.opBody(c.do("POST", apiPath("/captured-patterns/"+cpID+"/approval"), ""), 202).Id); got.Status != "succeeded" {
		t.Fatalf("approval ended %+v", got)
	}
	cp := c.pattern()
	if cp.State != gen.CapturedPatternStateApproved || !cp.Usable || cp.Approval == nil || cp.Approval.By != "client" ||
		cp.Approval.Proof != op.Target || cp.Approval.At.Before(at.Add(-time.Minute)) || cp.Approval.At.After(c.r.clock.Now().Add(time.Minute)) {
		t.Errorf("after approval: state %s usable %v approval %+v, want approved, usable, by client at now with proof %s", cp.State, cp.Usable, cp.Approval, op.Target)
	}
	c.problem(c.do("PUT", apiPath("/captured-patterns/"+cpID+"/parameters"), `{"parameters":[]}`), 409, "CapturedPatternApproved")
	if got := c.waitOp(c.opBody(c.do("POST", apiPath("/captured-patterns/"+cpID+"/approval"), ""), 202).Id); got.Status != "succeeded" {
		t.Errorf("approving an approved pattern ended %+v, want it to change nothing and succeed", got)
	}
	if again := c.pattern(); cpJSON(t, again.Approval) != cpJSON(t, cp.Approval) || again.State != gen.CapturedPatternStateApproved {
		t.Errorf("approving again changed the approval: %+v then %+v", cp.Approval, again.Approval)
	}
	// an approved pattern may be proved again at any time; the state stays approved
	again := c.prove("proof-two")
	c.waitEnded(again.Target, "done")
	if got := c.pattern(); got.State != gen.CapturedPatternStateApproved || len(got.Proofs) != 2 {
		t.Errorf("after a new proof: state %s with %d proofs, want approved with 2", got.State, len(got.Proofs))
	}
}
