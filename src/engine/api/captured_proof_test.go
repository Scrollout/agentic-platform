// Feature 011, T006 (the proof cases): a proof is capture -> POST /captured-patterns/{id}/proof-slice
// -> startRun of that slice, run on the engine rig with the real Run workflow (the durable test
// service), the step worker and the checker faked, through HTTP and the generated types only.
// Written before the code (T007, T029) by a test author, from spec FR-004 to FR-006, FR-011, the
// data model (Proof, States), the contract and T006. They compile against the tree as it is.
//
// WHAT THESE CASES NEED OF THE RIG (they cannot pass before it has it; none of it is changed
// here, an existing helper changes only with the owner's approval, ADR 0029):
//   - durable_service_test.go registers the WriteProject activity next to the others and maps the
//     new RunStart fields (the captured pattern's fill input, `proof`, the no-reuse flag) onto
//     durable.RunInput; its activitiesOn gives the activities a History that is a machine.Writer
//     (noHistory gains Write, which writes nothing and answers the files it was given, and the
//     Activities get a `Captured` source of the parameters) and the artifact store of the
//     template. Without it a fill step cannot run in the rig. See fill_proof_test.go in package
//     durable for the activity's shape.
//   - The source run's files: the fake worker below gives tests, code and witnesses framed files
//     (canonical.Framed), as a project worker's accepted files are, so a capture can read them.
//
// COVERED HERE: a proof runs on the proof slice with no registered fill worker and no model call;
// its RunStarted and run name the captured pattern, `chosen`, the source run, `proof: true` and
// the values; it passes on equal tests/code/witnesses hashes (an empty witnesses output included)
// and generated bytes that differ do not fail it; a failing check, expiry, cancellation fail it
// naming the check or the end; an interrupted run leaves it running; a second proof reuses nothing;
// the states and the busy and approval rules. NOT COVERED (no seam through HTTP; see the report):
// a planted byte change of a template file, the lost start answer, the proof with no Proof record
// on read, `PUT /parameters` between the start's 202 and its RunStarted, and a proof under another
// method.

