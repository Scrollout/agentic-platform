// A proof under way is running and never passed before its recorded end, also across an engine
// restart; its run continues and the proof then passes.
func TestAProofInterruptedByAnEngineRestartContinuesAndPassesOnlyAtItsEnd(t *testing.T) {
	c := newCP(t)
	c.capture()
	gate := make(chan struct{})
	c.set(func() { c.gate = gate })
	var once sync.Once
	t.Cleanup(func() { once.Do(func() { close(gate) }) })
	op := c.prove("proof-app")
	if p := c.lastProof(c.pattern()); p.Outcome != gen.ProofOutcomeRunning {
		t.Fatalf("the proof of a run that has not ended = %+v, want running", p)
	}
	c.boot() // the engine restarts over the same store; the workflow goes on
	if p := c.lastProof(c.pattern()); p.Outcome == gen.ProofOutcomePassed {
		t.Fatalf("the proof is passed after the restart with the run not ended: %+v", p)
	}
	once.Do(func() { close(gate) })
	c.waitEnded(op.Target, "done")
	if p := c.lastProof(c.pattern()); p.Outcome != gen.ProofOutcomePassed || len(c.pattern().Proofs) != 1 {
		t.Errorf("the proof after the run's end = %+v (%d proofs), want one, passed", p, len(c.pattern().Proofs))
	}
	c.boot()
	if cp := c.pattern(); len(cp.Proofs) != 1 || cp.Proofs[0].Outcome != gen.ProofOutcomePassed || cp.State != gen.CapturedPatternStateProven {
		t.Errorf("after another restart the captured pattern = %+v, want the one passed proof and state proven", cp)
	}
}

// A second proof under the same method reuses no earlier result: every step and check runs again.
func TestASecondProofReusesNoEarlierResultAndRunsEveryStep(t *testing.T) {
	c := newCP(t)
	c.capture()
	c.mu.Lock()
	c.sourceChecks = c.checks
	c.mu.Unlock()
	first := c.prove("proof-one")
	c.waitEnded(first.Target, "done")
	c.mu.Lock()
	checks := c.checks
	c.mu.Unlock()
	calls := c.w.callCount()
	second := c.prove("proof-two")
	c.waitEnded(second.Target, "done")
	for _, e := range c.allEvents(second.Target) {
		if e.Kind == "ResultReused" {
			t.Errorf("the second proof reused the result of step %s", e.Step)
		}
	}
	if got := c.w.callCount() - calls; got != 2 {
		t.Errorf("the second proof made %d worker calls, want 2 (every procedure step again)", got)
	}
	c.mu.Lock()
	again := c.checks - checks
	c.mu.Unlock()
	if again != checks-c.sourceChecks {
		t.Errorf("the second proof ran %d checks, the first %d: every check must run again", again, checks-c.sourceChecks)
	}
	cp := c.pattern()
	if len(cp.Proofs) != 2 || cp.Proofs[0].Run != first.Target || cp.Proofs[1].Run != second.Target ||
		cp.Proofs[0].Outcome != gen.ProofOutcomePassed || cp.Proofs[1].Outcome != gen.ProofOutcomePassed {
		t.Errorf("proofs = %+v, want two passed ones, newest last", cp.Proofs)
	}
}

