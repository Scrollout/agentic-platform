// T004 (feature 009): the generate procedure writes gen/declared.go, the one home in Go of every
// value the approved contract declares (catalogue README, "Declared values"; check contract,
// runProcedure). These tests fix what the output holds, how the names avoid the other files of
// gen/, that the output is repeatable and builds, that the two step checks that judge it pass on
// it and fail on a planted violation, and that a contract the collector cannot read refuses the
// step with a reason that says why.
//
// The expected file is written out here by hand from the README's rules, not computed with the
// code under test; one test also compares it with checks.RenderDeclared(checks.DeclaredValues(..))
// so the three owners of the rule (procedure, collector, check) cannot drift apart.

