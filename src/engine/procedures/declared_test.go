const declaredCollisionExpected = declaredHeader + `
// DeclaredQRxMaxLength_2 is declared at "/components/schemas/Q/properties/rx/maxLength".
const DeclaredQRxMaxLength_2 = 9

// DeclaredQRxMaxLength_3 is declared at "/components/schemas/QRx/maxLength".
const DeclaredQRxMaxLength_3 = 5
`

// generateDeclared runs the generate procedure on contract with the real toolchain.
func generateDeclared(t *testing.T, contract []byte) procedures.Result {
	t.Helper()
	res, err := procedures.Generate(context.Background(), genConfig(t, "template"), genInputs(contract))
	if err != nil {
		t.Fatal(err)
	}
	if !res.Completed {
		t.Fatalf("not completed: %s", res.Reason)
	}
	if len(res.Outputs) != 1 {
		t.Fatalf("want one output, got %d", len(res.Outputs))
	}
	return res
}

func outputFile(t *testing.T, res procedures.Result, p string) []byte {
	t.Helper()
	for _, f := range res.Outputs[0].Files {
		if f.Path == p {
			return f.Content
		}
	}
	t.Fatalf("the output has no %s", p)
	return nil
}

// topLevelNames are the names declared at the top level of the .go files in gen/ other than
// declared.go: functions (not methods), types, constants and variables.
func topLevelNames(t *testing.T, res procedures.Result) map[string]bool {
	t.Helper()
	taken := map[string]bool{}
	fset := token.NewFileSet()
	for _, f := range res.Outputs[0].Files {
		if path.Dir(f.Path) != "gen" || !strings.HasSuffix(f.Path, ".go") || f.Path == declaredPath {
			continue
		}
		af, err := parser.ParseFile(fset, f.Path, f.Content, parser.SkipObjectResolution)
		if err != nil {
			t.Fatalf("%s: %v", f.Path, err)
		}
		for _, d := range af.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil {
					taken[d.Name.Name] = true
				}
			case *ast.GenDecl:
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.TypeSpec:
						taken[s.Name.Name] = true
					case *ast.ValueSpec:
						for _, n := range s.Names {
							taken[n.Name] = true
						}
					}
				}
			}
		}
	}
	return taken
}

// writeOutput writes the output's files, and the contract as api/openapi.yaml, below dir.
func writeOutput(t *testing.T, dir string, res procedures.Result, contract []byte) {
	t.Helper()
	files := append([]procedures.File{{Path: "api/openapi.yaml", Content: contract}}, res.Outputs[0].Files...)
	for _, f := range files {
		p := filepath.Join(dir, filepath.FromSlash(f.Path))
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, f.Content, 0o600); err != nil {
			t.Fatal(err)
		}
	}
}

// The output holds gen/declared.go, exactly as the README states it.
func TestGenerateWritesDeclaredValues(t *testing.T) {
	contract := readTestdata(t, "declared", "contract.yaml")
	res := generateDeclared(t, contract)
	got := outputFile(t, res, declaredPath)
	if string(got) != declaredNotesExpected {
		t.Fatalf("gen/declared.go:\n--- got ---\n%s\n--- want ---\n%s", got, declaredNotesExpected)
	}
}

// The collector, the renderer and the procedure agree: the file is RenderDeclared of
// DeclaredValues(contract, the names of the other gen/ files).
func TestGenerateDeclaredEqualsRenderOfCollector(t *testing.T) {
	contract := readTestdata(t, "declared", "contract.yaml")
	res := generateDeclared(t, contract)
	values, err := checks.DeclaredValues(contract, topLevelNames(t, res))
	if err != nil {
		t.Fatalf("DeclaredValues: %v", err)
	}
	if want := checks.RenderDeclared(values); string(outputFile(t, res, declaredPath)) != string(want) {
		t.Fatalf("gen/declared.go is not RenderDeclared of the collector's values:\n--- got ---\n%s\n--- want ---\n%s",
			outputFile(t, res, declaredPath), want)
	}
}

// A name taken by oapi-codegen's output (a schema with that Go type name) or already given to an
// earlier value gets the next free suffix, in document order.
func TestGenerateDeclaredNamesAvoidOtherNames(t *testing.T) {
	contract := []byte(declaredCollisionContract)
	res := generateDeclared(t, contract)
	got := string(outputFile(t, res, declaredPath))
	if got != declaredCollisionExpected {
		t.Fatalf("gen/declared.go:\n--- got ---\n%s\n--- want ---\n%s", got, declaredCollisionExpected)
	}
	if taken := topLevelNames(t, res); !taken["DeclaredQRxMaxLength"] || taken["DeclaredQRxMaxLength_2"] {
		t.Fatalf("the fixture no longer makes oapi-codegen take DeclaredQRxMaxLength: %v", taken)
	}
	values, err := checks.DeclaredValues(contract, topLevelNames(t, res))
	if err != nil {
		t.Fatalf("DeclaredValues: %v", err)
	}
	if want := checks.RenderDeclared(values); got != string(want) {
		t.Fatalf("gen/declared.go is not RenderDeclared of the collector's values:\n%s\nvs\n%s", got, want)
	}
}

// A contract that declares no value gives the header and the package clause only.
func TestGenerateDeclaredNoValues(t *testing.T) {
	res := generateDeclared(t, readTestdata(t, "contract.yaml"))
	if got := string(outputFile(t, res, declaredPath)); got != declaredHeader {
		t.Fatalf("gen/declared.go of a contract without declared values:\n got %q\nwant %q", got, declaredHeader)
	}
}

// Two generations give the same bytes, gen/declared.go included.
func TestGenerateDeclaredRepeatable(t *testing.T) {
	contract := readTestdata(t, "declared", "contract.yaml")
	a, b := generateDeclared(t, contract), generateDeclared(t, contract)
	if !reflect.DeepEqual(a, b) {
		t.Fatal("generating twice gave different bytes or hashes")
	}
	if len(outputFile(t, a, declaredPath)) == 0 {
		t.Fatal("gen/declared.go is empty")
	}
}

// The project made of the output builds from vendor/ alone, with the constants in it.
func TestGenerateDeclaredBuilds(t *testing.T) {
	contract := readTestdata(t, "declared", "contract.yaml")
	res := generateDeclared(t, contract)
	if len(outputFile(t, res, declaredPath)) == 0 {
		t.Fatal("gen/declared.go is empty")
	}
	dir := t.TempDir()
	writeOutput(t, dir, res, contract)
	cmd := exec.Command("go", "build", "./...")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOPROXY=off", "GOWORK=off", "GOFLAGS=-mod=vendor", "CGO_ENABLED=0", "GOMODCACHE="+t.TempDir())
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("go build ./...: %v\n%s", err, out)
	}
}

func allPass(rs []checks.CheckResult) bool {
	for _, r := range rs {
		if !r.Passed {
			return false
		}
	}
	return len(rs) > 0
}

// GenerationRepeatable (go generate again, compare gen/) and DeclaredValuesGenerated pass on the
// output; DeclaredValuesGenerated fails on a planted violation (an edited, a missing, and a stale
// gen/declared.go) and on an approved contract it cannot read.
func TestGenerateDeclaredPassesTheStepChecks(t *testing.T) {
	contract := readTestdata(t, "declared", "contract.yaml")
	res := generateDeclared(t, contract)
	dir := t.TempDir()
	writeOutput(t, dir, res, contract)
	// go generate runs `oapi-codegen` from PATH.
	t.Setenv("PATH", filepath.Dir(oapiCodegen(t))+string(os.PathListSeparator)+os.Getenv("PATH"))

	if rs := checks.GenerationDrift(checks.NewGoRunner(), dir); !allPass(rs) {
		t.Fatalf("GenerationRepeatable on the output: %+v", rs)
	}
	rs := checks.DeclaredValuesGenerated(dir, contract)
	if !allPass(rs) {
		t.Fatalf("DeclaredValuesGenerated on the output: %+v", rs)
	}
	for _, r := range rs {
		if r.Part != "project" || r.Check != "DeclaredValuesGenerated" {
			t.Errorf("result names part %q check %q, want project and DeclaredValuesGenerated", r.Part, r.Check)
		}
	}

	p := filepath.Join(dir, "gen", "declared.go")
	// Planted: a hand edit.
	edited := strings.Replace(declaredNotesExpected, "= 280", "= 281", 1)
	if edited == declaredNotesExpected {
		t.Fatal("the planted edit changed nothing")
	}
	if err := os.WriteFile(p, []byte(edited), 0o600); err != nil {
		t.Fatal(err)
	}
	if rs := checks.DeclaredValuesGenerated(dir, contract); allPass(rs) {
		t.Fatalf("DeclaredValuesGenerated passed on an edited gen/declared.go: %+v", rs)
	}
	// Planted: the file is missing.
	if err := os.Remove(p); err != nil {
		t.Fatal(err)
	}
	if rs := checks.DeclaredValuesGenerated(dir, contract); allPass(rs) || !strings.Contains(joinReasons(rs), "declared.go") {
		t.Fatalf("DeclaredValuesGenerated must fail naming the missing gen/declared.go: %+v", rs)
	}
	// Planted: the file belongs to another contract (the approved one declares more).
	if err := os.WriteFile(p, []byte(declaredHeader), 0o600); err != nil {
		t.Fatal(err)
	}
	if rs := checks.DeclaredValuesGenerated(dir, contract); allPass(rs) {
		t.Fatalf("DeclaredValuesGenerated passed on a gen/declared.go without the approved contract's values: %+v", rs)
	}
	// An approved contract that does not parse fails closed.
	if err := os.WriteFile(p, []byte(declaredNotesExpected), 0o600); err != nil {
		t.Fatal(err)
	}
	if rs := checks.DeclaredValuesGenerated(dir, []byte("a: 1\na: 2\n")); allPass(rs) {
		t.Fatalf("DeclaredValuesGenerated passed on an approved contract with a duplicate key: %+v", rs)
	}
	// Restored: it passes again, so the failures above came from the plants.
	if rs := checks.DeclaredValuesGenerated(dir, contract); !allPass(rs) {
		t.Fatalf("DeclaredValuesGenerated after restoring the file: %+v", rs)
	}
}

func joinReasons(rs []checks.CheckResult) string {
	var s []string
	for _, r := range rs {
		s = append(s, r.Reason)
	}
	return strings.Join(s, "; ")
}

// A contract the collector cannot read (the fit conditions' reading: one YAML document, no
// duplicate key) is Completed false with no output and a reason that says why. The second
// document is one oapi-codegen alone would accept (it reads the first), so only the collector
// refuses it.
func TestGenerateRefusesAContractTheCollectorRejects(t *testing.T) {
	valid := string(readTestdata(t, "declared", "contract.yaml"))
	cases := []struct {
		name, contract string
		reasonHas      []string // every one must appear, lower-cased
	}{
		{"a second YAML document", valid + "---\nmaxLength: 3\n", []string{"document"}},
		{"a duplicate key", strings.Replace(valid, "          maxLength: 280\n", "          maxLength: 280\n          maxLength: 281\n", 1), []string{"maxlength"}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if c.contract == valid {
				t.Fatal("the fixture was not changed")
			}
			res, err := procedures.Generate(context.Background(), genConfig(t, "template"), genInputs([]byte(c.contract)))
			if err != nil {
				t.Fatalf("a contract that cannot be read is Completed false, not an error: %v", err)
			}
			if res.Completed || len(res.Outputs) != 0 {
				t.Fatalf("want Completed false and no outputs, got %+v", res)
			}
			low := strings.ToLower(res.Reason)
			for _, w := range c.reasonHas {
				if !strings.Contains(low, w) {
					t.Errorf("the reason must say why (contain %q): %q", w, res.Reason)
				}
			}
			if strings.Contains(res.Reason, "/tmp") || strings.Contains(res.Reason, os.TempDir()) {
				t.Errorf("a reason names project paths only: %q", res.Reason)
			}
		})
	}
}
