// ---- generation, cached per fixture ----

type rcGenerated struct {
	res      procedures.Result
	contract []byte
}

var (
	rcMu    sync.Mutex
	rcCache = map[string]rcGenerated{}
)

func rcTemplate(t *testing.T) string {
	t.Helper()
	abs, err := filepath.Abs(filepath.Join("..", "..", "catalogue", "api-feature-go", "template"))
	if err != nil {
		t.Fatal(err)
	}
	return abs
}

// rcRun runs the generate procedure on a fixture with the template folder tpl, not cached.
func rcRun(t *testing.T, fixture, tpl string) (procedures.Result, []byte, error) {
	t.Helper()
	contract := readTestdata(t, "requests", fixture)
	cfg := procedures.GenerateConfig{OapiCodegen: oapiCodegen(t), Template: tpl, Env: goEnv()}
	res, err := procedures.Generate(context.Background(), cfg, genInputs(contract))
	return res, contract, err
}

// rcGenerate is the generation of a fixture with the real template, made once per test run.
func rcGenerate(t *testing.T, fixture string) (procedures.Result, []byte) {
	t.Helper()
	rcMu.Lock()
	defer rcMu.Unlock()
	if g, ok := rcCache[fixture]; ok {
		return g.res, g.contract
	}
	res, contract, err := rcRun(t, fixture, rcTemplate(t))
	if err != nil {
		t.Fatal(err)
	}
	if !res.Completed {
		t.Fatalf("generating %s: not completed: %s", fixture, res.Reason)
	}
	if len(res.Outputs) != 1 {
		t.Fatalf("want one output, got %d", len(res.Outputs))
	}
	rcCache[fixture] = rcGenerated{res, contract}
	return res, contract
}

func rcFile(t *testing.T, res procedures.Result, p string) []byte {
	t.Helper()
	for _, f := range res.Outputs[0].Files {
		if f.Path == p {
			return f.Content
		}
	}
	t.Fatalf("the generated project has no %s", p)
	return nil
}

func rcTemplateFile(t *testing.T, rel string) []byte {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(rcTemplate(t), filepath.FromSlash(rel)))
	if err != nil {
		t.Fatalf("the template must hold %s: %v", rel, err)
	}
	return b
}

