// GenerationRepeatable (go generate again, compare gen/, with the template named in
// oapi-codegen.yaml) and RequestShapesGenerated pass on the output of both fixtures;
// RequestShapesGenerated fails on planted violations and on a contract it cannot read.
func TestRequestCheckStepChecksPass(t *testing.T) {
	for _, fixture := range []string{"notes.yaml", "shapes.yaml"} {
		t.Run(fixture, func(t *testing.T) {
			res, contract := rcGenerate(t, fixture)
			dir := t.TempDir()
			writeOutput(t, dir, res, contract)
			t.Setenv("PATH", filepath.Dir(oapiCodegen(t))+string(os.PathListSeparator)+os.Getenv("PATH"))

			if rs := checks.GenerationDrift(checks.NewGoRunner(), dir); !allPass(rs) {
				t.Fatalf("GenerationRepeatable on the output: %+v", rs)
			}
			rs := checks.RequestShapesGenerated(dir, contract)
			if !allPass(rs) {
				t.Fatalf("RequestShapesGenerated on the output: %+v", rs)
			}
			for _, r := range rs {
				if r.Part != "project" || r.Check != "RequestShapesGenerated" {
					t.Errorf("result names part %q check %q, want project and RequestShapesGenerated", r.Part, r.Check)
				}
			}

			p := filepath.Join(dir, filepath.FromSlash(rcShapesPath))
			orig, err := os.ReadFile(p)
			if err != nil {
				t.Fatal(err)
			}
			// planted: a hand edit
			if err := os.WriteFile(p, append(append([]byte(nil), orig...), []byte("\n// edited\n")...), 0o600); err != nil { //nolint:gosec // test-only path under t.TempDir()
				t.Fatal(err)
			}
			if rs := checks.RequestShapesGenerated(dir, contract); allPass(rs) || !strings.Contains(joinReasons(rs), "request_shapes.go") {
				t.Fatalf("RequestShapesGenerated must fail naming the edited file: %+v", rs)
			}
			// planted: the file is missing
			if err := os.Remove(p); err != nil {
				t.Fatal(err)
			}
			if rs := checks.RequestShapesGenerated(dir, contract); allPass(rs) || !strings.Contains(joinReasons(rs), "request_shapes.go") {
				t.Fatalf("RequestShapesGenerated must fail naming the missing file: %+v", rs)
			}
			// planted: the file of another contract
			other, _ := rcGenerate(t, map[string]string{"notes.yaml": "shapes.yaml", "shapes.yaml": "notes.yaml"}[fixture])
			if err := os.WriteFile(p, rcFile(t, other, rcShapesPath), 0o600); err != nil {
				t.Fatal(err)
			}
			if rs := checks.RequestShapesGenerated(dir, contract); allPass(rs) {
				t.Fatalf("RequestShapesGenerated passed on the shapes of another contract: %+v", rs)
			}
			// a contract that does not parse fails closed
			if err := os.WriteFile(p, orig, 0o600); err != nil { //nolint:gosec // test-only path under t.TempDir()
				t.Fatal(err)
			}
			if rs := checks.RequestShapesGenerated(dir, []byte("a: 1\na: 2\n")); allPass(rs) {
				t.Fatalf("RequestShapesGenerated passed on a contract with a duplicate key: %+v", rs)
			}
			// restored: it passes again, so the failures came from the plants
			if rs := checks.RequestShapesGenerated(dir, contract); !allPass(rs) {
				t.Fatalf("RequestShapesGenerated after restoring the file: %+v", rs)
			}
		})
	}
}

// Without gen/std-http-handler.tmpl in the template oapi-codegen would fetch the name as a URL:
// the generation must fail and name the file.
func TestRequestCheckMissingHandlerTemplateFailsGeneration(t *testing.T) {
	src := rcTemplate(t)
	if _, err := os.Stat(filepath.Join(src, "gen", "std-http-handler.tmpl")); err != nil {
		t.Fatalf("the template must hold gen/std-http-handler.tmpl: %v", err)
	}
	copyDir := filepath.Join(t.TempDir(), "template")
	err := filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		dst := filepath.Join(copyDir, rel)
		if d.IsDir() {
			return os.MkdirAll(dst, 0o750)
		}
		if rel == filepath.Join("gen", "std-http-handler.tmpl") {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		return os.WriteFile(dst, b, 0o600) //nolint:gosec // test-only path under t.TempDir()
	})
	if err != nil {
		t.Fatal(err)
	}
	res, _, genErr := rcRun(t, "notes.yaml", copyDir)
	said := res.Reason
	if genErr != nil {
		said += " " + genErr.Error()
	}
	if genErr == nil && res.Completed {
		t.Fatal("the generation completed although gen/std-http-handler.tmpl is absent from the template")
	}
	if !strings.Contains(said, "std-http-handler.tmpl") {
		t.Fatalf("the failure must name gen/std-http-handler.tmpl, got %q", said)
	}
}

