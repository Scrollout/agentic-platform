// ---- [integer, number], which oapi-codegen cannot generate: hand-built request shapes ----

func TestRequestCheckIntegerOrNumber(t *testing.T) {
	str := &checks.RequestShape{Types: []string{"string"}}
	obj := &checks.RequestShape{
		Types: []string{"object"},
		Properties: []checks.Member{
			{Name: "m", Shape: &checks.RequestShape{Types: []string{"integer", "number"}}},
			{Name: "k", Shape: &checks.RequestShape{Types: []string{"number", "integer"}}},
			{Name: "i", Shape: &checks.RequestShape{Types: []string{"integer"}}},
			{Name: "s", Shape: str},
		},
	}
	bodies := []checks.RequestBody{
		{Key: "POST /x", Required: true, Shape: obj},
		{Key: "POST /y", Required: true, Shape: &checks.RequestShape{Types: []string{"integer", "number"}}},
	}
	rendered := checks.RenderRequestShapes(bodies)
	if len(rendered) == 0 {
		t.Fatal("RenderRequestShapes gave no bytes")
	}
	dir := t.TempDir()
	put := func(rel string, b []byte) {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, b, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	put("go.mod", []byte("module example.com/rcmini\n\ngo 1.26\n"))
	put("gen/requests.go", rcTemplateFile(t, "gen/requests.go"))
	put(rcShapesPath, rendered)
	put("gen/rc_export.go", []byte(rcMiniExport))
	put("cmd/rcmini/main.go", []byte(rcMiniProgram))
	servers := rcStart(t, rcBuild(t, dir, "./cmd/rcmini", false), 1)

	x, y := "POST /x", "POST /y"
	orNumber := "an integer or a number"
	rcRunCases(t, servers, []rcCase{
		rcPass("m: 1.0 is kept as sent", x, `{"m":1.0}`, ""),
		rcPass("m: 1e999999 is kept as sent", x, `{"m":1e999999}`, ""),
		rcPass("m: 1.5 is kept", x, `{"m":1.50}`, ""),
		rcPass("m: a long integer", x, `{"m":1`+strings.Repeat("0", 60)+`}`, ""),
		rcPass("k: the types in the other order", x, `{"k":2.0}`, ""),
		rcRefuse("m: a string", x, `{"m":"1"}`, rcMember("/m", "must be "+orNumber)),
		rcRefuse("m: null", x, `{"m":null}`, rcMember("/m", "must be "+orNumber)),
		rcRefuse("k: a string", x, `{"k":"1"}`, rcMember("/k", "must be a number or an integer")),
		rcPass("i beside m: only the integer is written again", x, `{"m":1.0,"i":1.0,"x":1}`, `{"m":1.0,"i":1}`),
		rcPass("a root of both: 1.0 as sent", y, `1.0`, ""),
		{name: "a root of both: exact", op: y, body: `1e3`, status: 501, want: `1e3`, exact: true},
		rcRefuse("a root of both: a string", y, `"a"`, "the request body must be "+orNumber),
		rcRefuse("a root of both: null", y, `null`, "the request body must be "+orNumber),
	})
}
