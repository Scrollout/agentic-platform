// T004 (feature 010): failing tests, by a separate author, for the request check of a generated
// project (catalogue README, "Request check"; specs/010-strict-requests/contracts/strict-requests.md).
// The generate procedure writes gen/request_shapes.go, the template holds gen/requests.go and
// gen/std-http-handler.tmpl, and every registration of the generated handler is wrapped by
// refuseMalformed("<METHOD> <path>", ...). A program built from a generated project is served and
// asked, through gen.Handler, gen.HandlerFromMux and gen.HandlerWithOptions, for every case the
// README's table names; a recording handler (a gen.ServerInterface written here) shows what the
// operation receives.
//
// Fixtures: testdata/requests/notes.yaml (the evals' notes contract) and
// testdata/requests/shapes.yaml (nested objects and arrays, additionalProperties: false, integer,
// type lists with null, no type, no properties, an optional body, recursion). oapi-codegen v2.8.2
// cannot generate a multi-type list other than with "null" ("unhandled Schema type"), so the
// [integer, number] rule is tested in a small project of hand-built request shapes (the template's
// requests.go and checks.RenderRequestShapes) in TestRequestCheckIntegerOrNumber.
//
// Assumptions where the README is silent (see the report): a body's members are compared as
// decoded JSON with number text kept, not in member order (the README does not fix the order of
// the written members); a sign is not a digit when counting the 32 digits; a zero with a huge
// exponent (0e99999999999999999999) is written 0.
//
// Helpers here are prefixed rc, so they clash with no other test file.

