const rcShapesPath = "gen/request_shapes.go"

func rcCheckFiles(t *testing.T, fixture string, wantBodies int, registrations []string) {
	t.Helper()
	res, contract := rcGenerate(t, fixture)

	bodies, err := checks.RequestShapes(contract)
	if err != nil {
		t.Fatalf("RequestShapes(%s): %v", fixture, err)
	}
	if len(bodies) != wantBodies {
		t.Fatalf("RequestShapes(%s) found %d request bodies, want %d", fixture, len(bodies), wantBodies)
	}
	want := checks.RenderRequestShapes(bodies)
	if len(want) == 0 {
		t.Fatal("RenderRequestShapes gave no bytes")
	}
	if got := rcFile(t, res, rcShapesPath); !bytes.Equal(got, want) {
		t.Fatalf("%s is not RenderRequestShapes of the contract's bodies:\n--- got ---\n%s\n--- want ---\n%s", rcShapesPath, got, want)
	}
	if !strings.HasPrefix(string(want), "// Code generated by the generate procedure from api/openapi.yaml. DO NOT EDIT.\n\npackage gen\n") {
		t.Errorf("%s does not start with the generated-file header and package clause:\n%.200s", rcShapesPath, want)
	}

	// the template's own files reach the project byte for byte
	for _, p := range []string{"gen/requests.go", "gen/std-http-handler.tmpl"} {
		if got := rcFile(t, res, p); !bytes.Equal(got, rcTemplateFile(t, p)) {
			t.Errorf("%s of the project differs from the template's", p)
		}
	}
	if !strings.Contains(string(rcTemplateFile(t, "gen/requests.go")), "func refuseMalformed(key string, next http.HandlerFunc) http.HandlerFunc") {
		t.Error("the template's gen/requests.go lacks func refuseMalformed(key string, next http.HandlerFunc) http.HandlerFunc")
	}
	tmpl := string(rcTemplateFile(t, "gen/std-http-handler.tmpl"))
	first, _, _ := strings.Cut(tmpl, "\n")
	if !strings.HasPrefix(first, "{{/*") || !strings.HasSuffix(strings.TrimSpace(first), "*/}}") || !strings.Contains(first, "oapi-codegen v2.8.2") {
		t.Errorf("the template's first line must be a template comment naming oapi-codegen v2.8.2, got %q", first)
	}

	// every registration of api.gen.go is wrapped, and the template's comment is not written
	api := string(rcFile(t, res, "gen/api.gen.go"))
	var lines, wrapped int
	for _, l := range strings.Split(api, "\n") {
		if strings.Contains(l, "m.HandleFunc(") {
			lines++
			if strings.Contains(l, "refuseMalformed(") {
				wrapped++
			}
		}
	}
	if lines != len(registrations) || wrapped != lines {
		t.Errorf("api.gen.go has %d registrations, %d of them calling refuseMalformed; want %d, all wrapped", lines, wrapped, len(registrations))
	}
	for _, r := range registrations {
		if !strings.Contains(api, "refuseMalformed("+r+")") {
			t.Errorf("api.gen.go lacks refuseMalformed(%s)", r)
		}
	}
	for _, s := range []string{"copied from oapi-codegen", "{{/*", "*/}}"} {
		if strings.Contains(api, s) {
			t.Errorf("api.gen.go holds the template's comment line (%q)", s)
		}
	}
}

