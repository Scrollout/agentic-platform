func rcTreeCases() []rcCase {
	op := "POST /tree"
	// a chain of depth levels of children, each node holding a value
	chain := func(depth int, junk string) string {
		var b strings.Builder
		for i := 0; i < depth; i++ {
			b.WriteString(`{"value":1,` + junk + `"children":[`)
		}
		b.WriteString(`{"value":1}`)
		for i := 0; i < depth; i++ {
			b.WriteString(`]}`)
		}
		return b.String()
	}
	next := func(depth int) string {
		return strings.Repeat(`{"value":1,"next":`, depth) + `{"value":1}` + strings.Repeat(`}`, depth)
	}
	return []rcCase{
		rcPass("tree: a leaf", op, `{"value":1}`, ""),
		{name: "tree: 2000 levels of children", op: op, body: chain(2000, ""), status: 501, want: chain(2000, ""), exact: true},
		{name: "tree: 2000 levels of next", op: op, body: next(2000), status: 501, want: next(2000), exact: true},
		rcPass("tree: undeclared removed at every level", op, chain(30, `"junk":{"a":[1]},`), chain(30, "")),
		rcRefuse("tree: a wrong value two levels down", op,
			`{"value":1,"children":[{"value":1,"children":[{"value":"x"}]}]}`, rcMember("/children/0/children/0/value", "must be an integer")),
		rcRefuse("tree: a missing value through next", op, `{"value":1,"next":{}}`, rcMember("/next/value", "is required")),
		rcRefuse("tree: a wrong value through next", op, `{"value":1,"next":{"value":1,"next":{"value":"x"}}}`, rcMember("/next/next/value", "must be an integer")),
		rcRefuse("tree: children is an object", op, `{"value":1,"children":{}}`, rcMember("/children", "must be an array")),
		rcRefuse("tree: a child is null", op, `{"value":1,"children":[null]}`, rcMember("/children/0", "must be an object")),
		rcRefuse("tree: 2000 levels, then a type error", op, strings.Replace(chain(2000, ""), `{"value":1}`+strings.Repeat(`]}`, 2000), `{"value":true}`+strings.Repeat(`]}`, 2000), 1),
			rcMember(strings.Repeat("/children/0", 2000)+"/value", "must be an integer")),
	}
}

