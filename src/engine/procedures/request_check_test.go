// rcServer is one served handler: its base URL and the prefix its routes have.
type rcServer struct {
	name, url, prefix string
	recording         bool
}

// rcStart runs the built program and reads the address of each server it prints.
func rcStart(t *testing.T, bin string, n int) []rcServer {
	t.Helper()
	cmd := exec.Command(bin)
	out, err := cmd.StdoutPipe()
	if err != nil {
		t.Fatal(err)
	}
	cmd.Stderr = os.Stderr
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = cmd.Process.Kill(); _ = cmd.Wait() })
	var servers []rcServer
	sc := bufio.NewScanner(out)
	done := make(chan struct{})
	go func() {
		defer close(done)
		for len(servers) < n && sc.Scan() {
			f := strings.Fields(sc.Text())
			if len(f) != 2 {
				continue
			}
			s := rcServer{name: f[0], url: f[1], recording: f[0] == "recording"}
			if f[0] == "options" {
				s.prefix = "/api"
			}
			servers = append(servers, s)
		}
	}()
	select {
	case <-done:
	case <-time.After(30 * time.Second):
		t.Fatal("the test program did not print its servers")
	}
	if len(servers) != n {
		t.Fatalf("the test program printed %d servers, want %d", len(servers), n)
	}
	return servers
}

func rcGoEnv(t *testing.T, vendor bool) []string {
	env := append(os.Environ(), "GOPROXY=off", "GOWORK=off", "CGO_ENABLED=0", "GOMODCACHE="+t.TempDir())
	if vendor {
		env = append(env, "GOFLAGS=-mod=vendor")
	}
	return env
}

func rcBuild(t *testing.T, dir, pkg string, vendor bool) string {
	t.Helper()
	bin := filepath.Join(t.TempDir(), "rcprogram")
	cmd := exec.Command("go", "build", "-o", bin, pkg)
	cmd.Dir = dir
	cmd.Env = rcGoEnv(t, vendor)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("go build %s: %v\n%s", pkg, err, out)
	}
	return bin
}

// rcServe writes the generated project of a fixture with the program, builds it offline from
// vendor/ and starts it; methods are the recording handler's methods.
func rcServe(t *testing.T, fixture, methods string) []rcServer {
	t.Helper()
	res, contract := rcGenerate(t, fixture)
	dir := t.TempDir()
	writeOutput(t, dir, res, contract)
	mod := regexp.MustCompile(`(?m)^module\s+(\S+)`).FindStringSubmatch(string(rcFile(t, res, "go.mod")))[1]
	src := strings.NewReplacer("%MODULE%", mod, "%METHODS%", methods).Replace(rcProgram)
	p := filepath.Join(dir, "cmd", "rcserve", "main.go")
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}
	return rcStart(t, rcBuild(t, dir, "./cmd/rcserve", true), 4)
}

// ---- asking ----

type rcResp struct {
	status int
	ctype  string
	body   []byte
	seen   string
	took   time.Duration
}

var rcClient = &http.Client{Timeout: 60 * time.Second}

func rcDo(t *testing.T, s rcServer, op, ct string, body []byte) rcResp {
	t.Helper()
	method, path, _ := strings.Cut(op, " ")
	var rd io.Reader
	if body != nil {
		rd = bytes.NewReader(body)
	}
	req, err := http.NewRequest(method, s.url+s.prefix+path, rd)
	if err != nil {
		t.Fatal(err)
	}
	if body != nil && ct != "-" {
		if ct == "" {
			ct = "application/json"
		}
		req.Header.Set("Content-Type", ct)
	}
	start := time.Now()
	resp, err := rcClient.Do(req)
	if err != nil {
		t.Fatalf("%s %s: %v", s.name, op, err)
	}
	defer func() { _ = resp.Body.Close() }()
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		t.Fatalf("%s %s: reading the answer: %v", s.name, op, err)
	}
	return rcResp{resp.StatusCode, resp.Header.Get("Content-Type"), b, resp.Header.Get("X-Seen-Length"), time.Since(start)}
}

// rcCase is one request and what the check does with it. status is 400 (refused, with msg) or 501
// (reaches the stub; the recording handler answers 200 with the body it reads, want).
type rcCase struct {
	name   string
	op     string // "POST /notes"
	ct     string // "" application/json, "-" none
	body   string
	nobody bool // send no body at all (a nil reader)
	status int
	msg    string
	want   string // the body the recording handler reads; "" means body as sent
	exact  bool   // compare want byte for byte, not as decoded JSON
	quick  bool   // must be answered within seconds
	noEcho bool   // the recording handler is the stub for this operation
	after  string // a request answered 501 after this one, on the same server
}

// rcCanon decodes JSON with numbers kept as written and writes it again with sorted members.
func rcCanon(b []byte) (string, error) {
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.UseNumber()
	var v any
	if err := dec.Decode(&v); err != nil {
		return "", err
	}
	if dec.More() {
		return "", fmt.Errorf("more than one value")
	}
	out, err := json.Marshal(v)
	return string(out), err
}

func rcRunCases(t *testing.T, servers []rcServer, cases []rcCase) {
	t.Helper()
	for _, c := range cases {
		for _, s := range servers {
			c, s := c, s
			t.Run(c.name+"/"+s.name, func(t *testing.T) {
				var body []byte
				if !c.nobody {
					body = []byte(c.body)
					if body == nil {
						body = []byte{}
					}
				}
				r := rcDo(t, s, c.op, c.ct, body)
				if c.quick && r.took > 5*time.Second {
					t.Errorf("answered after %v, want quickly", r.took)
				}
				switch c.status {
				case 400:
					if r.status != 400 {
						t.Fatalf("status %d (%.200s), want 400 %q", r.status, r.body, c.msg)
					}
					if r.ctype != "application/json" {
						t.Errorf("Content-Type %q, want application/json", r.ctype)
					}
					var m map[string]any
					if err := json.Unmarshal(r.body, &m); err != nil || len(m) != 1 {
						t.Fatalf("the answer %q is not {\"message\": ...}: %v", r.body, err)
					}
					if got, _ := m["message"].(string); got != c.msg {
						t.Errorf("message %q, want %q", got, c.msg)
					}
				case 501:
					if s.recording && !c.noEcho {
						if r.status != 200 {
							t.Fatalf("the handler was not reached: status %d (%.200s)", r.status, r.body)
						}
						want := c.want
						if want == "" {
							want = c.body
						}
						if c.exact {
							if string(r.body) != want {
								t.Errorf("the handler read %.300q, want %.300q", r.body, want)
							}
						} else {
							got, err1 := rcCanon(r.body)
							exp, err2 := rcCanon([]byte(want))
							if err1 != nil || err2 != nil {
								t.Fatalf("the handler read %.300q (%v), want %.300q (%v)", r.body, err1, want, err2)
							}
							if got != exp {
								t.Errorf("the handler read %.300s, want %.300s", got, exp)
							}
						}
						if r.seen != strconv.Itoa(len(r.body)) {
							t.Errorf("the handler saw Content-Length %q for a body of %d bytes", r.seen, len(r.body))
						}
					} else if r.status != 501 {
						t.Fatalf("status %d (%.200s), want 501: the request must reach the stub", r.status, r.body)
					}
				default:
					t.Fatalf("bad case status %d", c.status)
				}
				if c.after != "" {
					op, body, _ := strings.Cut(c.after, "|")
					if a := rcDo(t, s, op, "", []byte(body)); a.status != 501 && (!s.recording || a.status != 200) {
						t.Errorf("the next request %s was answered %d (%.200s)", op, a.status, a.body)
					}
				}
			})
		}
	}
}

// ---- case builders ----

func rcRefuse(name, op, body, msg string) rcCase {
	return rcCase{name: name, op: op, body: body, status: 400, msg: msg}
}

func rcPass(name, op, body, want string) rcCase {
	return rcCase{name: name, op: op, body: body, status: 501, want: want}
}

func rcMember(p, rest string) string { return "member " + strconv.Quote(p) + " " + rest }

// rcCut is a pointer cut to its first 64 runes.
func rcCut(p string) string {
	if r := []rune(p); len(r) > 64 {
		return string(r[:64])
	}
	return p
}

// rcPad is prefix, white space, suffix: exactly n bytes.
func rcPad(prefix, suffix string, n int) string {
	return prefix + strings.Repeat(" ", n-len(prefix)-len(suffix)) + suffix
}

