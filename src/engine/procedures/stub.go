package procedures

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

// stubFor writes gen/stub.go for the generated code in genDir: a type Stub that implements the
// generated ServerInterface and answers every operation 501 Not Implemented, the server the tests
// step's tests must fail against. It is derived from ServerInterface alone, so it is the same for
// the same generated code.
func stubFor(genDir string) ([]byte, error) {
	entries, err := os.ReadDir(genDir)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	for _, e := range entries { // in file name order
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(genDir, e.Name()), nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		if iface := serverInterface(f); iface != nil {
			return writeStub(fset, f, iface)
		}
	}
	return nil, errors.New("no ServerInterface in gen/ (oapi-codegen's std-http-server)")
}

func serverInterface(f *ast.File) *ast.InterfaceType {
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.TYPE {
			continue
		}
		for _, s := range g.Specs {
			if ts := s.(*ast.TypeSpec); ts.Name.Name == "ServerInterface" {
				if it, ok := ts.Type.(*ast.InterfaceType); ok {
					return it
				}
			}
		}
	}
	return nil
}

func writeStub(fset *token.FileSet, f *ast.File, iface *ast.InterfaceType) ([]byte, error) {
	// The generated file's imports by the name its code uses for them.
	imports := map[string]string{}
	for _, im := range f.Imports {
		p, err := strconv.Unquote(im.Path.Value)
		if err != nil {
			return nil, err
		}
		name := path.Base(p)
		if im.Name != nil {
			name = im.Name.Name
		}
		imports[name] = p
	}
	used := map[string]bool{"net/http": true}
	var methods bytes.Buffer
	for _, m := range iface.Methods.List {
		ft, ok := m.Type.(*ast.FuncType)
		if !ok || len(m.Names) != 1 || ft.Params == nil || len(ft.Params.List) == 0 || len(ft.Params.List[0].Names) == 0 {
			return nil, fmt.Errorf("ServerInterface has a member that is not a handler: %v", m.Names)
		}
		ast.Inspect(ft, func(n ast.Node) bool {
			if sel, ok := n.(*ast.SelectorExpr); ok {
				if id, ok := sel.X.(*ast.Ident); ok {
					p, ok := imports[id.Name]
					if !ok {
						return true
					}
					used[p] = true
				}
			}
			return true
		})
		var params bytes.Buffer
		if err := printer.Fprint(&params, fset, &ast.FuncType{Params: ft.Params}); err != nil {
			return nil, err
		}
		name, w := m.Names[0].Name, ft.Params.List[0].Names[0].Name
		fmt.Fprintf(&methods, "\n// %s answers 501 Not Implemented.\nfunc (Stub) %s%s {\n\t%s.WriteHeader(http.StatusNotImplemented)\n}\n", name, name, strings.TrimPrefix(params.String(), "func"), w)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by the api-feature-go generate procedure from ServerInterface. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\nimport (\n", f.Name.Name)
	names := make([]string, 0, len(imports))
	for n := range imports {
		names = append(names, n)
	}
	slices.SortFunc(names, func(a, b string) int { return strings.Compare(imports[a], imports[b]) })
	for _, n := range names {
		p := imports[n]
		if !used[p] {
			continue
		}
		if n == path.Base(p) {
			fmt.Fprintf(&b, "\t%q\n", p)
		} else {
			fmt.Fprintf(&b, "\t%s %q\n", n, p)
		}
	}
	b.WriteString(")\n\n// Stub answers every operation of the contract with 501 Not Implemented: the server the tests run\n// against before any code is written.\ntype Stub struct{}\n\nvar _ ServerInterface = Stub{}\n")
	b.Write(methods.Bytes())
	return format.Source(b.Bytes())
}
