package checks

// The declared values of the approved contract (catalogue README, "Declared values"; ADR 0084,
// ADR 0086): one collector that the generate procedure, DeclaredValuesGenerated and
// DeclaredValuesNotRepeated all use, so they cannot disagree about what a declared value is.

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/constant"
	"go/parser"
	"go/scanner"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"go.yaml.in/yaml/v3"
)

// Declared is one value the contract states under a schema keyword.
type Declared struct {
	// Pointer is the RFC 6901 JSON Pointer of the keyword's value, for example
	// /components/schemas/NewNote/properties/text/maxLength.
	Pointer string
	// Keyword is the schema keyword (maxLength ... const), or enum for an item of an enum.
	Keyword string
	// Kind is "number", "string", "bool" or "null", or "unjudged" for a number no Go constant
	// reads the same way (.inf, .nan, 010, 0x1F, 0o17, 1_000).
	Kind string
	// Text is the scalar's text as written in the contract.
	Text string
	// Value is the number or string; nil for bool, null and unjudged.
	Value constant.Value
	// Name is the Go constant in gen/declared.go; "" for enum items, bool, null and unjudged.
	Name string
}

// The kinds of a declared value.
const (
	kindNumber   = "number"
	kindString   = "string"
	kindBool     = "bool"
	kindNull     = "null"
	kindUnjudged = "unjudged"
)

// DeclaredFile is the generated file that holds the declared values as constants.
const DeclaredFile = "gen/declared.go"

const declaredHeader = "// Code generated by the generate procedure from api/openapi.yaml. DO NOT EDIT.\n\npackage gen\n"

// declaringKeywords are the schema keywords whose scalar value is a declared value.
var declaringKeywords = map[string]bool{
	"maxLength": true, "minLength": true, "maximum": true, "minimum": true,
	"exclusiveMaximum": true, "exclusiveMinimum": true, "maxItems": true, "minItems": true,
	"maxProperties": true, "minProperties": true, "multipleOf": true, "default": true, "const": true,
}

// unnamedSegments are the pointer segments a constant's name leaves out.
var unnamedSegments = map[string]bool{
	"components": true, "schemas": true, "properties": true, "paths": true, "content": true, "schema": true,
}

// numberText is a number's text, normalised, that Go reads as YAML does.
var numberText = regexp.MustCompile(`^-?(0|[1-9][0-9]*)(\.[0-9]*)?([eE][-+]?[0-9]+)?$`)

// DeclaredValues finds every declared value of contract (the YAML text), in document order, and
// names them, avoiding the names in taken (the top-level names of the other files in gen/).
// An error means the text is not one YAML document without duplicate keys.
func DeclaredValues(contract []byte, taken map[string]bool) ([]Declared, error) {
	root, why := readContract(string(contract))
	if why != "" {
		return nil, errors.New(why)
	}
	var out []Declared
	var walk func(n *yaml.Node, ptr string)
	walk = func(n *yaml.Node, ptr string) {
		switch n.Kind {
		case yaml.MappingNode:
			for i := 0; i+1 < len(n.Content); i += 2 {
				k, v := n.Content[i], n.Content[i+1]
				if k.Kind != yaml.ScalarNode || k.Value == "<<" || k.Value == "example" || k.Value == "examples" || strings.HasPrefix(k.Value, "x-") {
					continue
				}
				p := ptr + "/" + pointerSegment(k.Value)
				switch {
				case declaringKeywords[k.Value] && v.Kind == yaml.ScalarNode:
					out = append(out, declared(p, k.Value, v))
				case k.Value == "enum" && v.Kind == yaml.SequenceNode:
					for j, item := range v.Content {
						if item.Kind == yaml.ScalarNode {
							out = append(out, declared(p+"/"+strconv.Itoa(j), "enum", item))
						}
					}
				default:
					walk(v, p)
				}
			}
		case yaml.SequenceNode:
			for j, item := range n.Content {
				walk(item, ptr+"/"+strconv.Itoa(j))
			}
		}
		// Alias nodes are not followed: the value under an anchor is found at the anchor.
	}
	walk(root, "")
	used := map[string]bool{}
	for i := range out {
		d := &out[i]
		if d.Keyword == "enum" || (d.Kind != kindNumber && d.Kind != kindString) {
			continue
		}
		base := constantName(d.Pointer)
		name := base
		for n := 2; used[name] || taken[name]; n++ {
			name = base + "_" + strconv.Itoa(n)
		}
		used[name] = true
		d.Name = name
	}
	return out, nil
}

// declared reads one scalar under keyword at pointer p.
func declared(p, keyword string, v *yaml.Node) Declared {
	d := Declared{Pointer: p, Keyword: keyword, Text: v.Value}
	switch v.ShortTag() {
	case "!!str":
		d.Kind, d.Value = kindString, constant.MakeString(v.Value)
	case "!!bool":
		d.Kind = kindBool
	case "!!null":
		d.Kind = kindNull
	case "!!int", "!!float":
		d.Kind = kindUnjudged
		if norm, ok := normalNumber(v.Value); ok {
			if val := numberValue(norm); val != nil {
				d.Kind, d.Value = kindNumber, val
			}
		}
	default:
		d.Kind = kindUnjudged
	}
	return d
}

// normalNumber is a number's text without a leading + and with 0 before a leading . (or -.),
// and whether Go reads it as YAML does.
func normalNumber(text string) (string, bool) {
	t := strings.TrimPrefix(text, "+")
	switch {
	case strings.HasPrefix(t, "."):
		t = "0" + t
	case strings.HasPrefix(t, "-."):
		t = "-0" + t[1:]
	}
	return t, numberText.MatchString(t)
}

// numberValue is the exact value of a normalised number's text.
func numberValue(norm string) constant.Value {
	neg := strings.HasPrefix(norm, "-")
	lit := strings.TrimPrefix(norm, "-")
	kind := token.INT
	if strings.ContainsAny(lit, ".eE") {
		kind = token.FLOAT
	}
	v := constant.MakeFromLiteral(lit, kind, 0)
	if v.Kind() == constant.Unknown {
		return nil
	}
	if neg {
		v = constant.UnaryOp(token.SUB, v, 0)
	}
	return v
}

// pointerSegment encodes one JSON Pointer segment (RFC 6901).
func pointerSegment(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "~", "~0"), "/", "~1")
}

// constantName is the Go name of the value at pointer p, before any suffix.
func constantName(p string) string {
	var b strings.Builder
	b.WriteString("Declared")
	for _, seg := range strings.Split(p, "/")[1:] {
		if unnamedSegments[seg] {
			continue
		}
		seg = strings.ReplaceAll(strings.ReplaceAll(seg, "~1", "/"), "~0", "~")
		upper := true
		for _, r := range seg {
			if (r < 'a' || r > 'z') && (r < 'A' || r > 'Z') && (r < '0' || r > '9') {
				upper = true
				continue
			}
			if upper && r >= 'a' && r <= 'z' {
				r -= 'a' - 'A'
			}
			upper = false
			b.WriteRune(r)
		}
	}
	return b.String()
}

// RenderDeclared is gen/declared.go for values: the same bytes for the same values.
func RenderDeclared(values []Declared) []byte {
	var b strings.Builder
	b.WriteString(declaredHeader)
	for _, d := range values {
		if d.Name == "" {
			continue
		}
		var lit string
		switch d.Kind {
		case kindString:
			lit = strconv.Quote(constant.StringVal(d.Value))
		case kindNumber:
			lit, _ = normalNumber(d.Text)
		default:
			continue
		}
		fmt.Fprintf(&b, "\n// %s is declared at %q.\nconst %s = %s\n", d.Name, d.Pointer, d.Name, lit)
	}
	return []byte(b.String())
}

// GenNames is the set of top-level names declared by the Go files in genDir other than
// gen/declared.go and test files: the names a declared constant must not take. A missing folder
// has none; a file that does not parse is an error.
func GenNames(genDir string) (map[string]bool, error) {
	names := map[string]bool{}
	entries, err := os.ReadDir(genDir)
	if errors.Is(err, os.ErrNotExist) {
		return names, nil
	}
	if err != nil {
		return nil, errors.New("gen/ cannot be listed")
	}
	fset := token.NewFileSet()
	for _, e := range entries {
		n := e.Name()
		if e.IsDir() || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") || n == filepath.Base(DeclaredFile) {
			continue
		}
		src, err := os.ReadFile(filepath.Join(genDir, n)) //nolint:gosec // a file of the project's gen/
		if err != nil {
			return nil, fmt.Errorf("gen/%s cannot be read", n)
		}
		f, err := parser.ParseFile(fset, "gen/"+n, src, parser.SkipObjectResolution)
		if err != nil {
			return nil, fmt.Errorf("%s does not parse as Go", parseErrorAt("gen/"+n, err))
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil {
					names[d.Name.Name] = true
				}
			case *ast.GenDecl:
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.TypeSpec:
						names[s.Name.Name] = true
					case *ast.ValueSpec:
						for _, id := range s.Names {
							names[id.Name] = true
						}
					}
				}
			}
		}
	}
	return names, nil
}

// projectDeclared is the approved contract's values, named as gen/declared.go names them in
// project; a failing result says what could not be read.
func projectDeclared(check, project string, approvedContract []byte) ([]Declared, *CheckResult) {
	taken, err := GenNames(filepath.Join(project, "gen"))
	if err != nil {
		r := fail(check, "the project's gen/ cannot be read: "+err.Error())
		return nil, &r
	}
	values, err := DeclaredValues(approvedContract, taken)
	if err != nil {
		r := fail(check, "the approved contract cannot be read: "+err.Error())
		return nil, &r
	}
	return values, nil
}

// DeclaredValuesGenerated passes when the project's gen/declared.go equals RenderDeclared of the
// approved contract's values (named avoiding the project's other gen/ files' top-level names).
// approvedContract is the contract's YAML text.
func DeclaredValuesGenerated(project string, approvedContract []byte) []CheckResult {
	const check = "DeclaredValuesGenerated"
	values, bad := projectDeclared(check, project, approvedContract)
	if bad != nil {
		return []CheckResult{*bad}
	}
	n := 0
	for _, d := range values {
		if d.Name != "" {
			n++
		}
	}
	got, err := fs.ReadFile(os.DirFS(project), DeclaredFile)
	if errors.Is(err, os.ErrNotExist) {
		return []CheckResult{fail(check, DeclaredFile+" is missing; the generate procedure writes it from the approved contract")}
	}
	if err != nil {
		return []CheckResult{fail(check, DeclaredFile+" cannot be read: "+err.Error())}
	}
	if !bytes.Equal(got, RenderDeclared(values)) {
		return []CheckResult{fail(check, fmt.Sprintf("%s differs from the %d declared values of the approved contract; it is generated, never edited", DeclaredFile, n))}
	}
	return []CheckResult{pass(check, fmt.Sprintf("%s equals the %d declared values of the approved contract", DeclaredFile, n))}
}

// judgedGoFiles are the project's .go files that writable matches, test files aside, in path
// order, parsed; a failing result names a file that cannot be read or parsed.
func judgedGoFiles(check, project string, writable []string) (*token.FileSet, []string, []*ast.File, []CheckResult) {
	files := map[string][]byte{}
	var paths []string
	root := os.DirFS(project) // paths relative to the project, so no error names a host path
	err := fs.WalkDir(root, ".", func(rel string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(rel, ".go") || strings.HasSuffix(rel, "_test.go") || !MatchGlob(writable, rel) {
			return nil
		}
		if !d.Type().IsRegular() {
			return fmt.Errorf("%s is not a regular file", rel)
		}
		b, err := fs.ReadFile(root, rel)
		if err != nil {
			return err
		}
		files[rel] = b
		paths = append(paths, rel)
		return nil
	})
	if err != nil {
		return nil, nil, nil, []CheckResult{fail(check, "the project cannot be read: "+err.Error())}
	}
	sort.Strings(paths)
	fset := token.NewFileSet()
	var parsed []*ast.File
	var bad []CheckResult
	for _, p := range paths {
		f, err := parser.ParseFile(fset, p, files[p], parser.SkipObjectResolution)
		if err != nil {
			bad = append(bad, fail(check, parseErrorAt(p, err)+" does not parse as Go, so it cannot be judged"))
			continue
		}
		parsed = append(parsed, f)
	}
	if bad != nil {
		return nil, nil, nil, bad
	}
	return fset, paths, parsed, nil
}

// parseErrorAt is where a Go file fails to parse, <file>:<line>:<column>, never the parser's
// message, which quotes the offending token (model-written text that may hold a credential).
func parseErrorAt(file string, err error) string {
	var list scanner.ErrorList
	if errors.As(err, &list) && len(list) > 0 {
		return fmt.Sprintf("%s:%d:%d", file, list[0].Pos.Line, list[0].Pos.Column)
	}
	return file
}
